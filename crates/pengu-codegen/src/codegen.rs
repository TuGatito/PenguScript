fn is_primitive_method(krate: &HirCrate, program: &LProgram, def: DefId) -> bool {
    krate.impls.iter().any(|imp| {
        imp.methods.contains(&def)
            && program
                .functions
                .iter()
                .filter(|function| function.def == def)
                .any(|function| {
                    function_self_ty(krate, function).is_some_and(|ty| is_primitive(&ty))
                })
    })
}

/// Nombre del receptor dentro del cuerpo: `self` en `impl`, `__self` en las
/// funciones libres que representan métodos inherentes de primitivos.
fn self_name(krate: &HirCrate, function: &LFunction) -> &'static str {
    match function_self_ty(krate, function) {
        Some(ty) if is_primitive(&ty) => "__self",
        _ => "self",
    }
}

fn emit_function_body(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
    header: &str,
) {
    let _ = writeln!(out, "{header}");
    let self_local = self_local_index(krate, function.def);
    let live_in = ssa::liveness(function, self_local);
    let has_lifetime = live_in
        .iter()
        .flat_map(|fields| fields.iter())
        .any(|local| {
            function
                .locals
                .iter()
                .find(|candidate| candidate.id == *local)
                .is_some_and(|candidate| ty_has_ref(&candidate.ty))
        });
    let lifetime = if has_lifetime { "<'a>" } else { "" };
    let _ = writeln!(out, "    enum __State{lifetime} {{");
    for (id, fields) in live_in.iter().enumerate() {
        if fields.is_empty() {
            let _ = writeln!(out, "        B{id},");
        } else {
            let _ = write!(out, "        B{id} {{");
            for local in fields {
                let field = function.locals.iter().find(|l| l.id == *local);
                let ty = field
                    .map(|l| {
                        if has_lifetime {
                            ty_rust_state(&l.ty, krate)
                        } else {
                            local_decl_type(function, l, krate)
                        }
                    })
                    .unwrap_or_else(|| "()".to_owned());
                let _ = write!(out, " __l{local}: {ty},");
            }
            out.push_str(" },\n");
        }
    }
    out.push_str("    }\n");
    let entry_fields = &live_in[function.entry];
    if entry_fields.is_empty() {
        let _ = writeln!(out, "    let mut __state = __State::B{};", function.entry);
    } else {
        let _ = write!(out, "    let mut __state = __State::B{} {{", function.entry);
        for local in entry_fields {
            let param = function.params.iter().find(|p| p.local == *local);
            let value = if let Some(param) = param {
                rust_ident(&param.name)
            } else {
                // El bloque de entrada puede recibir un local que todavía no se
                // ha definido (p. ej. el resultado de un `match` anidado como
                // expresión). Construir el estado con `unreachable!()` saltaría
                // nada más crear el enum, así que los tipos con valor por
                // defecto arrancan en `Default::default()` (N48).
                let ty = function
                    .locals
                    .iter()
                    .find(|candidate| candidate.id == *local)
                    .map(|local| &local.ty);
                if ty.is_some_and(ty_has_default) {
                    "Default::default()".to_owned()
                } else {
                    "unreachable!()".to_owned()
                }
            };
            let _ = write!(out, " __l{local}: {value},");
        }
        out.push_str(" };\n");
    }
    if function.has_curse {
        out.push_str("    unsafe {\n");
    }
    out.push_str("    loop {\n        __state = match __state {\n");
    for block in &function.blocks {
        emit_ssa_block(out, krate, program, function, block, &live_in);
    }
    out.push_str("        };\n    }\n");
    if function.has_curse {
        out.push_str("    }\n");
    }
    out.push_str("}\n\n");
}

fn stmt_span(stmt: &LStmt) -> Option<pengu_span::Span> {
    match stmt {
        LStmt::Let(_, _, span)
        | LStmt::Assign(_, _, span)
        | LStmt::SetField(_, _, _, span)
        | LStmt::Eval(_, span)
        | LStmt::Destructure(_, _, span) => Some(*span),
    }
}

fn emit_ssa_block(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
    block: &pengu_lir::LBlock,
    live_in: &[BTreeSet<usize>],
) {
    let fields = &live_in[block.id];
    if fields.is_empty() {
        let _ = writeln!(out, "            __State::B{} => {{", block.id);
    } else {
        let _ = write!(out, "            __State::B{} {{", block.id);
        for local in fields {
            let _ = write!(out, " mut __l{local},");
        }
        out.push_str(" } => {\n");
    }
    let mut defined: BTreeSet<usize> = fields.iter().copied().collect();
    let self_local = self_local_index(krate, function.def);
    for stmt in &block.stmts {
        if let Some(span) = stmt_span(stmt) {
            let _ = writeln!(
                out,
                "                // @pengu-span {}:{}:{}",
                span.file.index(),
                span.start,
                span.end
            );
        }
        match stmt {
            LStmt::Let(index, expr, _) | LStmt::Assign(index, expr, _) => {
                let value = lower_expr(expr, krate, program, function);
                if defined.contains(index) {
                    let _ = writeln!(out, "                __l{index} = {value};");
                } else {
                    let ty = function
                        .locals
                        .iter()
                        .find(|l| l.id == *index)
                        .map(|l| local_decl_type(function, l, krate))
                        .unwrap_or_else(|| "()".to_owned());
                    let _ = writeln!(out, "                let mut __l{index}: {ty} = {value};");
                    defined.insert(*index);
                }
            }
            LStmt::SetField(index, field, value, _) => {
                let base = if self_local == Some(*index) {
                    self_name(krate, function).to_owned()
                } else {
                    format!("__l{index}")
                };
                let _ = writeln!(
                    out,
                    "                {}.{} = {};",
                    base,
                    rust_ident(field),
                    lower_expr(value, krate, program, function)
                );
            }
            LStmt::Eval(expr, _) => {
                let _ = writeln!(
                    out,
                    "                {};",
                    lower_expr(expr, krate, program, function)
                );
            }
            LStmt::Destructure(source, target, _) => {
                let mut leaves = Vec::new();
                let pattern = destructure_pattern(target, &mut leaves);
                let _ = writeln!(
                    out,
                    "                let {pattern} = {};",
                    lower_expr(source, krate, program, function)
                );
                for (i, target) in leaves.iter().enumerate() {
                    if defined.contains(target) {
                        let _ = writeln!(out, "                __l{target} = __d{i};");
                    } else {
                        let _ = writeln!(out, "                let mut __l{target} = __d{i};");
                        defined.insert(*target);
                    }
                }
            }
        }
    }
    match &block.term {
        LTerm::Goto(next) => {
            let _ = writeln!(
                out,
                "                {}",
                state_expr(*next, live_in, &defined, function, krate)
            );
        }
        LTerm::If(cond, then_block, else_block) => {
            let _ = writeln!(
                out,
                "                if {} {{ {} }} else {{ {} }}",
                lower_expr(cond, krate, program, function),
                state_expr(*then_block, live_in, &defined, function, krate),
                state_expr(*else_block, live_in, &defined, function, krate)
            );
        }
        LTerm::Return(Some(expr)) => {
            let _ = writeln!(
                out,
                "                return {};",
                lower_expr(expr, krate, program, function)
            );
        }
        LTerm::Return(None) => {
            if function.ret == Ty::Never {
                out.push_str("                unreachable!();\n");
            } else {
                out.push_str("                return;\n");
            }
        }
        LTerm::Panic(expr) => {
            let _ = writeln!(
                out,
                "                panic!(\"{{}}\", {});",
                lower_expr(expr, krate, program, function)
            );
        }
        LTerm::Next {
            iter,
            item,
            some,
            none,
        } => {
            let _ = writeln!(out, "                match __l{iter}.next() {{");
            let _ = writeln!(out, "                    Some(__v) => {{");
            let _ = writeln!(out, "                        let mut __l{item} = __v;");
            let mut some_defined = defined.clone();
            some_defined.insert(*item);
            let _ = writeln!(
                out,
                "                        {}",
                state_expr(*some, live_in, &some_defined, function, krate)
            );
            out.push_str("                    }\n");
            let _ = writeln!(out, "                    None => {{");
            let _ = writeln!(
                out,
                "                        {}",
                state_expr(*none, live_in, &defined, function, krate)
            );
            out.push_str("                    }\n                }\n");
        }
        LTerm::Unreachable => out.push_str("                unreachable!();\n"),
    }
    out.push_str("            }\n");
}

fn state_expr(
    block: usize,
    live_in: &[BTreeSet<usize>],
    defined: &BTreeSet<usize>,
    function: &LFunction,
    krate: &HirCrate,
) -> String {
    let fields = &live_in[block];
    if fields.is_empty() {
        return format!("__State::B{block}");
    }
    let mut out = format!("__State::B{block} {{");
    for local in fields {
        let value = if defined.contains(local) {
            format!("__l{local}")
        } else {
            // El checker de ownership/CFG debe impedir este camino; se deja
            // unreachable para que Rust no invente una inicialización.
            "unreachable!()".to_owned()
        };
        let _ = write!(out, " __l{local}: {value},");
    }
    out.push('}');
    let _ = (function, krate);
    out
}

fn lower_expr(expr: &LExpr, krate: &HirCrate, program: &LProgram, function: &LFunction) -> String {
    match expr {
        LExpr::Unit => "()".to_owned(),
        LExpr::Bool(value) => value.to_string(),
        LExpr::Int(value) => value.to_string(),
        LExpr::Float(value) => format!("{value:?}"),
        LExpr::Str(value) => {
            if value.len() >= 2 && value.starts_with('"') && value.ends_with('"') {
                value.clone()
            } else {
                format!("{value:?}")
            }
        }
        LExpr::Interpolate(parts) => {
            let mut pieces = Vec::new();
            for part in parts {
                match part {
                    pengu_lir::LStringPart::Text(text) => {
                        pieces.push(format!("{text:?}.to_string()"));
                    }
                    pengu_lir::LStringPart::Expr(expr) => {
                        pieces.push(format!(
                            "crate::__pengu_show(&{})",
                            lower_expr(expr, krate, program, function)
                        ));
                    }
                }
            }
            if pieces.is_empty() {
                "String::new()".to_owned()
            } else {
                format!("[{}].concat()", pieces.join(", "))
            }
        }
        LExpr::Local(index) => {
            if self_local_index(krate, function.def) == Some(*index) {
                self_name(krate, function).to_owned()
            } else {
                format!("__l{index}")
            }
        }
        LExpr::Binary(op, lhs, rhs) => {
            // `x == none` se emite como `x.is_none()`: así no hace falta que el
            // tipo del payload implemente `PartialEq`.
            if matches!(op, LBinOp::Eq | LBinOp::Ne) {
                let is_none = |expr: &LExpr| matches!(expr, LExpr::Primitive(name, args) if name == "none" && args.is_empty());
                if is_none(lhs) || is_none(rhs) {
                    let other = if is_none(lhs) { rhs } else { lhs };
                    let method = if matches!(op, LBinOp::Eq) {
                        "is_none"
                    } else {
                        "is_some"
                    };
                    return format!(
                        "({}).{method}()",
                        lower_expr(other, krate, program, function)
                    );
                }
            }
            format!(
                "({} {} {})",
                lower_expr(lhs, krate, program, function),
                bin_op(*op),
                lower_expr(rhs, krate, program, function)
            )
        }
        LExpr::TraitCall { pact, method, args } => {
            let path = def_path(krate, *pact);
            let args = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>();
            format!("{path}::{method}({})", args.join(", "))
        }
        LExpr::Unary(LUnOp::Neg, inner) => match inner.as_ref() {
            LExpr::Int(value) => format!("(-{value}i32)"),
            LExpr::Float(value) => format!("(-{value}f64)"),
            _ => format!("(-{})", lower_expr(inner, krate, program, function)),
        },
        LExpr::Unary(op, inner) => format!(
            "({}{})",
            un_op(*op),
            lower_expr(inner, krate, program, function)
        ),
        LExpr::FuncRef(def) | LExpr::ConstRef(def) => def_path(krate, *def),
        LExpr::CStringNew(arg) => format!(
            "::std::ffi::CString::new({}).map_err(|_| ())",
            lower_expr(arg, krate, program, function)
        ),
        LExpr::Call(def, type_args, args) => {
            let rendered = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>();
            let args = if krate
                .foreign_abis
                .get(def)
                .is_some_and(|abi| abi != "pengu")
            {
                let signature = krate.signatures.get(def);
                rendered
                    .iter()
                    .enumerate()
                    .map(|(index, text)| {
                        let cstr = signature
                            .and_then(|signature| signature.params.get(index))
                            .is_some_and(ast_is_cstr);
                        if cstr {
                            format!("({text}).as_ptr()")
                        } else {
                            text.clone()
                        }
                    })
                    .collect::<Vec<_>>()
                    .join(", ")
            } else {
                rendered.join(", ")
            };
            let name = if krate
                .foreign_abis
                .get(def)
                .is_some_and(|abi| abi == "pengu")
            {
                format!("crate::__pengu_std::{}", rust_ident(&krate.def(*def).name))
            } else if primitive_label(krate, *def).is_some() {
                // Función asociada de un primitivo (`String.from`).
                def_path_named(krate, *def, &primitive_fn_name(krate, *def))
            } else if let Some(path) = associated_builtin_path(krate, *def) {
                // Función asociada de un tipo integrado (`Vec.new` → `Vec::new`).
                format!("::{path}::{}", rust_ident(&krate.def(*def).name))
            } else if let Some(target) = inherent_impl_target(krate, program, *def, type_args) {
                // Función asociada de un `rune` (`File.open` → `File::open`).
                format!("{target}::{}", rust_ident(&krate.def(*def).name))
            } else {
                call_name(krate, program, *def, type_args)
            };
            if krate
                .foreign_abis
                .get(def)
                .is_some_and(|abi| abi != "pengu")
                && krate
                    .signatures
                    .get(def)
                    .is_some_and(|signature| ast_is_cstr(&signature.ret))
            {
                return format!("::std::ffi::CStr::from_ptr({name}({args}))");
            }
            format!("{name}({args})")
        }
        LExpr::Method {
            receiver,
            def,
            name,
            args,
        } => {
            let rendered = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>();
            if let Some(def) = def
                && let Some(label) = builtin_label(krate, *def)
            {
                // Método de un tipo integrado: paso directo a Rust, salvo los
                // que necesitan un ayudante genérico del runtime.
                let receiver = lower_borrowed(receiver, krate, program, function);
                let kind = krate
                    .signatures
                    .get(def)
                    .and_then(|signature| signature.receiver);
                let args = builtin_args(krate, *def, &rendered);
                if let Some(helper) = builtin_helper(label, name) {
                    let receiver = match kind {
                        Some(pengu_syntax::ast::Receiver::Mut) => format!("&mut ({receiver})"),
                        Some(pengu_syntax::ast::Receiver::Own) => format!("({receiver})"),
                        _ => format!("&({receiver})"),
                    };
                    let mut all = vec![receiver];
                    all.push(args);
                    let all = all.join(", ").trim_end_matches(", ").to_owned();
                    return format!("crate::__pengu_std::{helper}({all})");
                }
                return format!("({receiver}).{name}({args})");
            }
            if let Some(def) = def
                && is_primitive_method(krate, program, *def)
            {
                let mut all = Vec::with_capacity(rendered.len() + 1);
                all.push(lower_expr(receiver, krate, program, function));
                all.extend(rendered);
                let path = match primitive_label(krate, *def) {
                    Some(_) => def_path_named(krate, *def, &primitive_fn_name(krate, *def)),
                    None => def_path(krate, *def),
                };
                let receiver = krate
                    .signatures
                    .get(def)
                    .and_then(|signature| signature.receiver);
                if receiver == Some(pengu_syntax::ast::Receiver::Own) {
                    // Se pasa por valor.
                } else if receiver == Some(pengu_syntax::ast::Receiver::Mut) {
                    all[0] = format!("&mut {}", all[0]);
                } else if !primitive_is_copy(krate, *def) {
                    all[0] = format!("&{}", all[0]);
                }
                return format!("{path}({})", all.join(", "));
            }
            let args = rendered.join(", ");
            let receiver = match def
                .and_then(|def| krate.signatures.get(&def))
                .and_then(|signature| signature.receiver)
            {
                Some(pengu_syntax::ast::Receiver::Own) => {
                    lower_expr(receiver, krate, program, function)
                }
                Some(pengu_syntax::ast::Receiver::Mut) => {
                    lower_borrowed_mut(receiver, krate, program, function)
                }
                _ => lower_borrowed(receiver, krate, program, function),
            };
            format!("{receiver}.{name}({args})")
        }
        LExpr::VecAdapter {
            kind,
            base,
            args,
            ty,
        } => {
            let base = lower_expr(base, krate, program, function);
            let rendered = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>();
            match kind {
                pengu_lir::VecAdapterKind::Map => {
                    format!("Box::new(({base}).map(|__x| ({f})(__x)))", f = rendered[0])
                }
                pengu_lir::VecAdapterKind::Filter => format!(
                    "Box::new(({base}).filter_map(|__x| if ({f})(__x) {{ Some(__x) }} else {{ None }}))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Fold => format!(
                    "({base}).fold({init}, |__acc, __x| ({f})(__acc, __x))",
                    init = rendered[0],
                    f = rendered[1]
                ),
                pengu_lir::VecAdapterKind::Collect => {
                    format!("({base}).collect::<Vec<_>>()")
                }
                pengu_lir::VecAdapterKind::Count => format!("({base}).count()"),
                pengu_lir::VecAdapterKind::Last => format!("({base}).last()"),
                pengu_lir::VecAdapterKind::Nth => format!("({base}).nth({n})", n = rendered[0]),
                pengu_lir::VecAdapterKind::Sum => {
                    let item = ty
                        .as_ref()
                        .map_or_else(|| "_".to_owned(), |ty| ty_rust(ty, krate));
                    format!("({base}).sum::<{item}>()")
                }
                pengu_lir::VecAdapterKind::Min => format!("({base}).min()"),
                pengu_lir::VecAdapterKind::Max => format!("({base}).max()"),
                pengu_lir::VecAdapterKind::Any => {
                    format!("({base}).any(|__x| ({f})(__x))", f = rendered[0])
                }
                pengu_lir::VecAdapterKind::All => {
                    format!("({base}).all(|__x| ({f})(__x))", f = rendered[0])
                }
                pengu_lir::VecAdapterKind::Find => {
                    format!("({base}).find(|__x| ({f})(__x.clone()))", f = rendered[0])
                }
                pengu_lir::VecAdapterKind::Position => {
                    format!("({base}).position(|__x| ({f})(__x))", f = rendered[0])
                }
                pengu_lir::VecAdapterKind::Take => {
                    format!("Box::new(({base}).take({n}))", n = rendered[0])
                }
                pengu_lir::VecAdapterKind::Skip => {
                    format!("Box::new(({base}).skip({n}))", n = rendered[0])
                }
                pengu_lir::VecAdapterKind::StepBy => {
                    format!("Box::new(({base}).step_by({n}))", n = rendered[0])
                }
                // `Box<dyn Iterator>` no implementa `DoubleEndedIterator`, así que
                // `rev` materializa el iterador antes de invertirlo. El coste es
                // O(n) de memoria; el orden y el resultado son los mismos.
                pengu_lir::VecAdapterKind::Rev => {
                    format!("Box::new(({base}).collect::<Vec<_>>().into_iter().rev())")
                }
                pengu_lir::VecAdapterKind::FilterMap => format!(
                    "Box::new(({base}).filter_map(|__x| ({f})(__x)))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::FlatMap => format!(
                    "Box::new(({base}).flat_map(|__x| ({f})(__x)))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Flatten => format!("Box::new(({base}).flatten())"),
                pengu_lir::VecAdapterKind::Chain => {
                    format!("Box::new(({base}).chain({other}))", other = rendered[0])
                }
                pengu_lir::VecAdapterKind::TakeWhile => format!(
                    "Box::new(({base}).take_while(|__x| ({f})((*__x).clone())))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::SkipWhile => format!(
                    "Box::new(({base}).skip_while(|__x| ({f})((*__x).clone())))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Reduce => format!(
                    "({base}).reduce(|__a, __x| ({f})(__a, __x))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Product => {
                    let item = ty
                        .as_ref()
                        .map_or_else(|| "_".to_owned(), |ty| ty_rust(ty, krate));
                    format!("({base}).product::<{item}>()")
                }
                pengu_lir::VecAdapterKind::ForEach => {
                    format!(
                        "{{ ({base}).for_each(|__x| {{ ({f})(__x); }}); }}",
                        f = rendered[0]
                    )
                }
                pengu_lir::VecAdapterKind::Inspect => format!(
                    "Box::new(({base}).inspect(|__x| {{ ({f})((*__x).clone()); }}))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Fuse => format!("Box::new(({base}).fuse())"),
                pengu_lir::VecAdapterKind::MaxBy => format!(
                    "({base}).max_by(|__a, __x| ({f})((*__a).clone(), (*__x).clone()))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::StrChars => {
                    format!("Box::new(({base}).chars())")
                }
                pengu_lir::VecAdapterKind::StrBytes => format!("Box::new(({base}).bytes())"),
                pengu_lir::VecAdapterKind::StrCharIndices => {
                    format!("Box::new(({base}).char_indices())")
                }
                pengu_lir::VecAdapterKind::MinBy => format!(
                    "({base}).min_by(|__a, __x| ({f})((*__a).clone(), (*__x).clone()))",
                    f = rendered[0]
                ),
                pengu_lir::VecAdapterKind::Enumerate => format!("Box::new(({base}).enumerate())"),
                pengu_lir::VecAdapterKind::Zip => {
                    format!("Box::new(({base}).zip({other}))", other = rendered[0])
                }
            }
        }
        LExpr::Tuple(items) => {
            let items = items
                .iter()
                .map(|item| lower_expr(item, krate, program, function))
                .collect::<Vec<_>>()
                .join(", ");
            if items.contains(',') {
                format!("({items})")
            } else {
                format!("({items},)")
            }
        }
        LExpr::Closure {
            params,
            ret,
            body,
            captures,
        } => {
            let mut names = std::collections::HashMap::new();
            let mut rendered = Vec::new();
            for (name, local) in captures {
                let expression = function
                    .locals
                    .iter()
                    .find(|candidate| candidate.id == *local)
                    .filter(|candidate| ty_is_copy(&candidate.ty, krate))
                    .map_or_else(|| format!("&__l{local}"), |_| format!("__l{local}"));
                names.insert(name.clone(), expression);
            }
            for (name, ty) in params {
                let rust = rust_ident(name);
                names.insert(name.clone(), rust.clone());
                rendered.push(format!("{rust}: {}", ty_rust(ty, krate)));
            }
            // Constantes y variantes visibles dentro del cuerpo de la closure.
            for (name, value) in [
                ("Less", "::std::cmp::Ordering::Less"),
                ("Equal", "::std::cmp::Ordering::Equal"),
                ("Greater", "::std::cmp::Ordering::Greater"),
                ("none", "None"),
                ("true", "true"),
                ("false", "false"),
            ] {
                names
                    .entry(name.to_owned())
                    .or_insert_with(|| value.to_owned());
            }
            let body = lower_ast_block(body, &names);
            let ret = if *ret == Ty::Unit {
                String::new()
            } else {
                format!(" -> {}", ty_rust(ret, krate))
            };
            format!("Box::new(|{}|{ret} {{ {body} }})", rendered.join(", "))
        }
        LExpr::ClosureCall(callee, args) => {
            let args = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>()
                .join(", ");
            format!("({})({args})", lower_expr(callee, krate, program, function))
        }
        LExpr::CollectVec(expr) => {
            format!(
                "({}).into_iter().collect::<Vec<_>>()",
                lower_expr(expr, krate, program, function)
            )
        }
        LExpr::IntoIter(expr) => {
            format!(
                "Box::new(({}).into_iter())",
                lower_expr(expr, krate, program, function)
            )
        }
        LExpr::IterCloned(expr) => {
            format!(
                "Box::new(({}).clone().into_iter())",
                lower_expr(expr, krate, program, function)
            )
        }
        LExpr::Char(raw) | LExpr::ByteChar(raw) => raw.clone(),
        LExpr::Field(base, name) => {
            format!(
                "{}.{}",
                lower_borrowed(base, krate, program, function),
                rust_ident(name)
            )
        }
        LExpr::Index(base, index) => format!(
            "{}[{}]",
            lower_borrowed(base, krate, program, function),
            lower_expr(index, krate, program, function)
        ),
        LExpr::Array(items) => format!(
            "[{}]",
            items
                .iter()
                .map(|item| lower_expr(item, krate, program, function))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        LExpr::ArrayRepeat(value, count) => format!(
            "[{}; {}]",
            lower_expr(value, krate, program, function),
            count
        ),
        LExpr::Vector(items) => format!(
            "vec![{}]",
            items
                .iter()
                .map(|item| lower_expr(item, krate, program, function))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        LExpr::Map(entries) => {
            let entries = entries
                .iter()
                .map(|(key, value)| {
                    format!(
                        "({}, {})",
                        lower_expr(key, krate, program, function),
                        lower_expr(value, krate, program, function)
                    )
                })
                .collect::<Vec<_>>()
                .join(", ");
            format!("::std::collections::HashMap::from([{entries}])")
        }
        LExpr::Set(items) => {
            let items = items
                .iter()
                .map(|item| lower_expr(item, krate, program, function))
                .collect::<Vec<_>>()
                .join(", ");
            format!("::std::collections::HashSet::from([{items}])")
        }
        LExpr::Record {
            def,
            path,
            fields,
            base,
        } => {
            let (owner, variant) = def
                .and_then(|def| krate.variant_owner(def).map(|owner| (owner, def)))
                .map_or((None, None), |(owner, variant)| {
                    (Some(owner), Some(variant))
                });
            let type_name = if let Some(owner) = owner {
                let variant = variant.expect("variant");
                format!(
                    "{}::{}",
                    def_path(krate, owner),
                    rust_ident(&krate.defs[variant.index()].name)
                )
            } else if let Some(def) = def {
                def_path(krate, *def)
            } else {
                path.join("::")
            };
            if fields
                .iter()
                .all(|(name, _)| name.chars().all(|c| c.is_ascii_digit()))
                && base.is_none()
            {
                let args = fields
                    .iter()
                    .map(|(_, value)| lower_expr(value, krate, program, function))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{type_name}({args})")
            } else {
                let fields = fields
                    .iter()
                    .map(|(name, value)| {
                        format!(
                            "{}: {}",
                            rust_ident(name),
                            lower_expr(value, krate, program, function)
                        )
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                if let Some(base) = base {
                    format!(
                        "{type_name} {{ {fields}, ..{} }}",
                        lower_expr(base, krate, program, function)
                    )
                } else {
                    format!("{type_name} {{ {fields} }}")
                }
            }
        }
        LExpr::IsVariant(value, def) => {
            let path = variant_path(krate, *def);
            let fields = variant_fields(krate, *def);
            let pattern = if fields.is_empty() {
                path
            } else {
                format!("{path} {{ .. }}")
            };
            format!(
                "matches!(&{}, {pattern})",
                lower_borrowed(value, krate, program, function)
            )
        }
        LExpr::IsBuiltin(value, kind) => {
            let pattern = match kind {
                BuiltinVariant::Some => "Some(_)",
                BuiltinVariant::Ok => "Ok(_)",
                BuiltinVariant::Err => "Err(_)",
            };
            format!(
                "matches!(&{}, {pattern})",
                lower_borrowed(value, krate, program, function)
            )
        }
        LExpr::BuiltinField(value, kind) => {
            let pattern = match kind {
                BuiltinVariant::Some => "Some(__v0)",
                BuiltinVariant::Ok => "Ok(__v0)",
                BuiltinVariant::Err => "Err(__v0)",
            };
            format!(
                "match &{} {{ {pattern} => __v0.clone(), _ => unreachable!() }}",
                lower_borrowed(value, krate, program, function)
            )
        }
        LExpr::VariantField(value, def, index) => {
            let path = variant_path(krate, *def);
            let (field_name, tuple) = variant_field_info(krate, *def, *index);
            let pattern = if tuple {
                format!("{path}(__v0)")
            } else {
                format!("{path} {{ {field_name}: __v0, .. }}")
            };
            // El patrón se aplica sobre `&valor`, así que `__v0` es una
            // referencia al campo. Clonar evita mover un campo no-`Copy`
            // (p. ej. `String`) fuera de un préstamo (E0507).
            format!(
                "match &{} {{ {pattern} => __v0.clone(), _ => unreachable!() }}",
                lower_borrowed(value, krate, program, function)
            )
        }
        LExpr::Variant(def, args) => {
            let owner = krate.variant_owner(*def);
            let name = owner.map_or_else(
                || def_path(krate, *def),
                |owner| {
                    format!(
                        "{}::{}",
                        def_path(krate, owner),
                        rust_ident(&krate.defs[def.index()].name)
                    )
                },
            );
            match args {
                Some(args) => {
                    let rendered = args
                        .iter()
                        .map(|arg| lower_expr(arg, krate, program, function))
                        .collect::<Vec<_>>();
                    // Una variante con campos nombrados construida de forma
                    // posicional se emite con la sintaxis de struct de Rust.
                    match variant_adt(krate, *def) {
                        Some(variant) if !variant.tuple && !variant.fields.is_empty() => {
                            let fields = variant
                                .fields
                                .iter()
                                .zip(&rendered)
                                .map(|(field, value)| {
                                    format!("{}: {value}", rust_ident(&field.name))
                                })
                                .collect::<Vec<_>>()
                                .join(", ");
                            format!("{name} {{ {fields} }}")
                        }
                        _ => format!("{name}({})", rendered.join(", ")),
                    }
                }
                None => name,
            }
        }
        LExpr::Primitive(name, args) => {
            let rendered = args
                .iter()
                .map(|arg| lower_expr(arg, krate, program, function))
                .collect::<Vec<_>>();
            let args = rendered.join(", ");
            match name.as_str() {
                "some" => format!("Some({args})"),
                "none" => "None".to_owned(),
                "ok" => format!("Ok({args})"),
                "err" => format!("Err({args})"),
                "print" => format!("println!(\"{{}}\", crate::__pengu_show(&{args}))"),
                "format" => format!("crate::__pengu_show(&{args})"),
                "assert" if rendered.len() == 2 => format!(
                    "assert!({}, \"{{}}\", crate::__pengu_show(&{}))",
                    rendered[0], rendered[1]
                ),
                "panic" if rendered.len() == 1 => {
                    format!("panic!(\"{{}}\", crate::__pengu_show(&{}))", rendered[0])
                }
                "assert_eq" => format!("assert_eq!({args})"),
                "assert_ne" => format!("assert_ne!({args})"),
                "ordering_less" => "::std::cmp::Ordering::Less".to_owned(),
                "ordering_equal" => "::std::cmp::Ordering::Equal".to_owned(),
                "ordering_greater" => "::std::cmp::Ordering::Greater".to_owned(),
                _ => format!("{name}({args})"),
            }
        }
        LExpr::Cast(expr, ty) => {
            let source = match expr.as_ref() {
                LExpr::Int(value) => format!("{value}i32"),
                LExpr::Float(value) => format!("{value}f64"),
                _ => lower_expr(expr, krate, program, function),
            };
            format!("({source} as {})", ty_rust(ty, krate))
        }
        LExpr::Try(expr) => format!("({})?", lower_expr(expr, krate, program, function)),
        LExpr::Ref(mutable, expr) => format!(
            "&{}{}",
            if *mutable { "mut " } else { "" },
            lower_expr(expr, krate, program, function)
        ),
        LExpr::Range(start, end, inclusive) => match end {
            Some(end) => format!(
                "{}..{}{}",
                lower_expr(start, krate, program, function),
                if *inclusive { "=" } else { "" },
                lower_expr(end, krate, program, function)
            ),
            None => format!("{}..", lower_expr(start, krate, program, function)),
        },
    }
}

fn variant_path(krate: &HirCrate, def: DefId) -> String {
    krate.variant_owner(def).map_or_else(
        || def_path(krate, def),
        |owner| {
            format!(
                "{}::{}",
                def_path(krate, owner),
                rust_ident(&krate.defs[def.index()].name)
            )
        },
    )
}

fn variant_adt(krate: &HirCrate, def: DefId) -> Option<&pengu_hir::hir::AdtVariant> {
    let owner = krate.variant_owner(def)?;
    krate
        .adt(owner)?
        .variants
        .iter()
        .find(|variant| variant.def == def)
}

fn variant_fields(krate: &HirCrate, def: DefId) -> Vec<String> {
    variant_adt(krate, def)
        .map(|variant| {
            variant
                .fields
                .iter()
                .map(|field| field.name.clone())
                .collect()
        })
        .unwrap_or_default()
}

fn variant_field_info(krate: &HirCrate, def: DefId, index: u32) -> (String, bool) {
    variant_adt(krate, def).map_or_else(
        || ("_".to_owned(), true),
        |variant| {
            let field = variant.fields.get(index as usize);
            (
                field.map_or_else(|| "_".to_owned(), |field| field.name.clone()),
                variant.tuple,
            )
        },
    )
}

fn call_name(krate: &HirCrate, program: &LProgram, def: DefId, type_args: &[Ty]) -> String {
    if type_args.is_empty() {
        return def_path(krate, def);
    }
    program
        .instances
        .iter()
        .find(|instance| instance.def == def && instance.type_args == type_args)
        .map_or_else(
            || def_path(krate, def),
            |instance| def_path_named(krate, def, &rust_ident(&instance.name)),
        )
}

const fn bin_op(op: LBinOp) -> &'static str {
    match op {
        LBinOp::Add => "+",
        LBinOp::Sub => "-",
        LBinOp::Mul => "*",
        LBinOp::Div => "/",
        LBinOp::Rem => "%",
        LBinOp::Eq => "==",
        LBinOp::Ne => "!=",
        LBinOp::Lt => "<",
        LBinOp::Le => "<=",
        LBinOp::Gt => ">",
        LBinOp::Ge => ">=",
        LBinOp::And => "&&",
        LBinOp::Or => "||",
    }
}

const fn un_op(op: LUnOp) -> &'static str {
    match op {
        LUnOp::Neg => "-",
        LUnOp::Not => "!",
    }
}

fn ty_is_copy(ty: &Ty, krate: &HirCrate) -> bool {
    match ty {
        Ty::Bool
        | Ty::Int
        | Ty::I8
        | Ty::I16
        | Ty::I32
        | Ty::I64
        | Ty::Isize
        | Ty::U8
        | Ty::U16
        | Ty::U32
        | Ty::U64
        | Ty::Usize
        | Ty::Float
        | Ty::F32
        | Ty::F64
        | Ty::Char
        | Ty::Str
        | Ty::Unit
        | Ty::Never
        | Ty::Ptr(_)
        | Ty::CStr => true,
        Ty::Tuple(items) => items.iter().all(|item| ty_is_copy(item, krate)),
        Ty::Array(inner, _) => ty_is_copy(inner, krate),
        Ty::Option(inner) => ty_is_copy(inner, krate),
        Ty::Result(ok, err) => ty_is_copy(ok, krate) && ty_is_copy(err, krate),
        Ty::Adt(def, args) => krate
            .adt(*def)
            .is_some_and(|adt| adt.is_copy && args.iter().all(|arg| ty_is_copy(arg, krate))),
        _ => false,
    }
}

/// Tipos que pueden inicializarse con `Default::default()` sin ambigüedad.
fn ty_has_default(ty: &Ty) -> bool {
    match ty {
        Ty::Bool
        | Ty::Char
        | Ty::Unit
        | Ty::Never
        | Ty::Int
        | Ty::I8
        | Ty::I16
        | Ty::I32
        | Ty::I64
        | Ty::Isize
        | Ty::U8
        | Ty::U16
        | Ty::U32
        | Ty::U64
        | Ty::Usize
        | Ty::F32
        | Ty::F64
        | Ty::String
        | Ty::Vec(_)
        | Ty::Map(_, _)
        | Ty::Set(_)
        | Ty::Option(_) => true,
        Ty::Tuple(items) => items.iter().all(ty_has_default),
        _ => false,
    }
}

fn local_decl_type(function: &LFunction, local: &pengu_lir::LLocal, krate: &HirCrate) -> String {
    if let Some((params, ret)) = closure_local_type(function, local) {
        return format!(
            "Box<dyn Fn({}) -> {}>",
            params
                .iter()
                .map(|param| ty_rust(param, krate))
                .collect::<Vec<_>>()
                .join(", "),
            ty_rust(&ret, krate)
        );
    }
    ty_rust(&local_type(function, local).unwrap_or(Ty::Unit), krate)
}

fn closure_local_type(function: &LFunction, local: &pengu_lir::LLocal) -> Option<(Vec<Ty>, Ty)> {
    for block in &function.blocks {
        for stmt in &block.stmts {
            if let pengu_lir::LStmt::Let(index, expr, _) = stmt {
                if *index == local.id {
                    if let pengu_lir::LExpr::Closure { params, ret, .. } = expr {
                        return Some((
                            params.iter().map(|(_, ty)| ty.clone()).collect(),
                            ret.clone(),
                        ));
                    }
                }
            }
        }
    }
    None
}

fn ty_has_ref(ty: &Ty) -> bool {
    match ty {
        Ty::Str | Ty::CStr | Ty::Ref(_, _) | Ty::Slice(_, _) => true,
        Ty::Tuple(items) => items.iter().any(ty_has_ref),
        Ty::Vec(item)
        | Ty::Set(item)
        | Ty::Option(item)
        | Ty::Array(item, _)
        | Ty::Box(item)
        | Ty::Rc(item)
        | Ty::Arc(item)
        | Ty::Iterator(item) => ty_has_ref(item),
        Ty::Map(key, value) => ty_has_ref(key) || ty_has_ref(value),
        Ty::Result(ok, err) => ty_has_ref(ok) || ty_has_ref(err),
        Ty::Fn(params, ret) => params.iter().any(ty_has_ref) || ty_has_ref(ret),
        Ty::Adt(_, args) => args.iter().any(ty_has_ref),
        _ => false,
    }
}

fn ty_rust_state(ty: &Ty, krate: &HirCrate) -> String {
    match ty {
        Ty::Str => "&'a str".to_owned(),
        Ty::CStr => "&'a ::std::ffi::CStr".to_owned(),
        Ty::Slice(inner, false) => format!("&'a [{}]", ty_rust_state(inner, krate)),
        Ty::Slice(inner, true) => format!("&'a mut [{}]", ty_rust_state(inner, krate)),
        Ty::Ref(inner, false) => format!("&'a {}", ty_rust_state(inner, krate)),
        Ty::Ref(inner, true) => format!("&'a mut {}", ty_rust_state(inner, krate)),
        Ty::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(|item| ty_rust_state(item, krate))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        Ty::Array(item, len) => {
            format!("[{}; {len}]", ty_rust_state(item, krate))
        }
        Ty::Vec(item) => format!("Vec<{}>", ty_rust_state(item, krate)),
        Ty::Map(key, value) => format!(
            "::std::collections::HashMap<{}, {}>",
            ty_rust_state(key, krate),
            ty_rust_state(value, krate)
        ),
        Ty::Set(item) => format!(
            "::std::collections::HashSet<{}>",
            ty_rust_state(item, krate)
        ),
        Ty::Option(item) => format!("Option<{}>", ty_rust_state(item, krate)),
        Ty::Result(ok, err) => format!(
            "Result<{}, {}>",
            ty_rust_state(ok, krate),
            ty_rust_state(err, krate)
        ),
        Ty::Box(item) => format!("Box<{}>", ty_rust_state(item, krate)),
        Ty::Rc(item) => format!("::std::rc::Rc<{}>", ty_rust_state(item, krate)),
        Ty::Arc(item) => format!("::std::sync::Arc<{}>", ty_rust_state(item, krate)),
        Ty::Adt(def, args) => {
            let name = if krate.defs.get(def.0 as usize).is_some() {
                def_path(krate, *def)
            } else {
                "Unknown".to_owned()
            };
            if args.is_empty() {
                name
            } else {
                format!(
                    "{name}<{}>",
                    args.iter()
                        .map(|item| ty_rust_state(item, krate))
                        .collect::<Vec<_>>()
                        .join(", ")
                )
            }
        }
        Ty::Iterator(item) => format!("Box<dyn Iterator<Item = {}>>", ty_rust_state(item, krate)),
        _ => ty_rust(ty, krate),
    }
}

fn local_type(function: &LFunction, local: &pengu_lir::LLocal) -> Option<Ty> {
    if local.ty != Ty::Error {
        return Some(local.ty.clone());
    }
    for block in &function.blocks {
        for stmt in &block.stmts {
            if let pengu_lir::LStmt::Let(index, expr, _) = stmt {
                if *index == local.id {
                    if let pengu_lir::LExpr::Closure { params, ret, .. } = expr {
                        return Some(Ty::Fn(
                            params.iter().map(|(_, ty)| ty.clone()).collect(),
                            Box::new(ret.clone()),
                        ));
                    }
                }
            }
        }
    }
    None
}

fn self_local_index(krate: &HirCrate, owner: DefId) -> Option<usize> {
    krate
        .bodies
        .iter()
        .find(|body| body.owner == owner)
        .and_then(|body| body.self_local.map(|local| local.index()))
}

fn lower_borrowed(
    expr: &LExpr,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
) -> String {
    if let LExpr::Local(index) = expr {
        if self_local_index(krate, function.def) == Some(*index) {
            return self_name(krate, function).to_owned();
        }
        return format!("__l{index}");
    }
    lower_expr(expr, krate, program, function)
}

fn lower_borrowed_mut(
    expr: &LExpr,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
) -> String {
    if let LExpr::Local(index) = expr {
        if self_local_index(krate, function.def) == Some(*index) {
            return self_name(krate, function).to_owned();
        }
        return format!("__l{index}");
    }
    format!("&mut {}", lower_expr(expr, krate, program, function))
}

/// Baja un bloque del AST a Rust para el cuerpo de una closure.
fn lower_ast_block(
    block: &pengu_syntax::ast::Block,
    params: &std::collections::HashMap<String, String>,
) -> String {
    use pengu_syntax::ast::{PatternKind, StmtKind};
    let mut out = String::from("{\n");
    let last = block.stmts.len();
    for (index, stmt) in block.stmts.iter().enumerate() {
        match &stmt.kind {
            StmtKind::Bind {
                mutable,
                pattern,
                value,
                ..
            } => {
                if let PatternKind::Path(path) = &pattern.kind {
                    if path.len() == 1 {
                        out.push_str(&format!(
                            "let {}{} = {};\n",
                            if *mutable { "mut " } else { "" },
                            rust_ident(&path[0]),
                            lower_ast_expr(value, params)
                        ));
                    }
                }
            }
            StmtKind::Assign { target, value } => {
                out.push_str(&format!(
                    "{} = {};\n",
                    lower_ast_expr(target, params),
                    lower_ast_expr(value, params)
                ));
            }
            StmtKind::Expr(expr) => {
                let rendered = lower_ast_expr(expr, params);
                if index + 1 == last {
                    out.push_str(&rendered);
                    out.push('\n');
                } else {
                    out.push_str(&rendered);
                    out.push_str(";\n");
                }
            }
            _ => {}
        }
    }
    out.push('}');
    out
}

fn lower_ast_expr(
    expr: &pengu_syntax::ast::Expr,
    params: &std::collections::HashMap<String, String>,
) -> String {
    use pengu_syntax::ast::{BinOp, ExprKind, UnOp};
    match &expr.kind {
        ExprKind::Unit => "()".to_owned(),
        ExprKind::None => "None".to_owned(),
        ExprKind::Bool(value) => value.to_string(),
        ExprKind::Int(raw) => raw.clone(),
        ExprKind::Float(raw) => raw.clone(),
        ExprKind::String(lit) => {
            use pengu_syntax::ast::StringPart;
            if let [StringPart::Text(text)] = lit.parts.as_slice() {
                return format!("{text:?}");
            }
            let mut pattern = String::new();
            let mut args = Vec::new();
            for part in &lit.parts {
                match part {
                    StringPart::Text(text) => {
                        pattern.push_str(&text.replace('{', "{{").replace('}', "}}"));
                    }
                    StringPart::Expr(inner) => {
                        pattern.push_str("{}");
                        args.push(format!(
                            "crate::__pengu_show(&{})",
                            lower_ast_expr(inner, params)
                        ));
                    }
                }
            }
            if args.is_empty() {
                format!("{pattern:?}")
            } else {
                format!("format!({pattern:?}, {})", args.join(", "))
            }
        }
        ExprKind::Record { path, fields, base } => {
            let name = path
                .iter()
                .map(|segment| rust_ident(segment))
                .collect::<Vec<_>>()
                .join("::");
            let mut parts = fields
                .iter()
                .map(|(field, value)| {
                    format!("{}: {}", rust_ident(field), lower_ast_expr(value, params))
                })
                .collect::<Vec<_>>();
            if let Some(base) = base {
                parts.push(format!("..{}", lower_ast_expr(base, params)));
            }
            format!("{name} {{ {} }}", parts.join(", "))
        }
        ExprKind::Char(raw) | ExprKind::ByteChar(raw) => raw.clone(),
        ExprKind::Path(segments) if segments.len() == 1 => match segments[0].as_str() {
            // Constructores de `Option`/`Result` sin argumentos y variantes de
            // `Ordering`: el cuerpo de una lambda se renderiza desde el AST, así
            // que aquí no hay resoluciones del HIR a las que preguntar.
            "none" => "None".to_owned(),
            "Less" => "::std::cmp::Ordering::Less".to_owned(),
            "Equal" => "::std::cmp::Ordering::Equal".to_owned(),
            "Greater" => "::std::cmp::Ordering::Greater".to_owned(),
            name => params
                .get(name)
                .cloned()
                .unwrap_or_else(|| rust_ident(name)),
        },
        ExprKind::Unary { op, expr } => {
            let op = match op {
                UnOp::Neg => "-",
                UnOp::Not => "!",
            };
            format!("({op}{})", lower_ast_expr(expr, params))
        }
        ExprKind::Binary { op, lhs, rhs } => {
            let op = match op {
                BinOp::Add => "+",
                BinOp::Sub => "-",
                BinOp::Mul => "*",
                BinOp::Div => "/",
                BinOp::Rem => "%",
                BinOp::Eq | BinOp::Is => "==",
                BinOp::Ne | BinOp::Isnt => "!=",
                BinOp::Lt => "<",
                BinOp::Le => "<=",
                BinOp::Gt => ">",
                BinOp::Ge => ">=",
                BinOp::And => "&&",
                BinOp::Or => "||",
                _ => "+",
            };
            format!(
                "({} {op} {})",
                lower_ast_expr(lhs, params),
                lower_ast_expr(rhs, params)
            )
        }
        ExprKind::Vector(items) => format!(
            "vec![{}]",
            items
                .iter()
                .map(|item| lower_ast_expr(item, params))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        ExprKind::Array(items) => format!(
            "[{}]",
            items
                .iter()
                .map(|item| lower_ast_expr(item, params))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        ExprKind::Tuple(items) => format!(
            "({})",
            items
                .iter()
                .map(|item| lower_ast_expr(item, params))
                .collect::<Vec<_>>()
                .join(", ")
        ),
        ExprKind::Field { base, name } => {
            format!("{}.{}", lower_ast_expr(base, params), rust_ident(name))
        }
        ExprKind::Index { base, index } => format!(
            "{}[{}]",
            lower_ast_expr(base, params),
            lower_ast_expr(index, params)
        ),
        ExprKind::If {
            cond,
            then_branch,
            else_branch,
            unless,
        } => {
            let cond = lower_ast_expr(cond, params);
            let cond = if *unless { format!("!({cond})") } else { cond };
            let then_branch = lower_ast_block(then_branch, params);
            match else_branch {
                Some(else_branch) => format!(
                    "if {cond} {then_branch} else {}",
                    lower_ast_block(else_branch, params)
                ),
                None => format!("if {cond} {then_branch}"),
            }
        }
        ExprKind::Call { callee, args } => {
            let rendered = args
                .iter()
                .map(|arg| lower_ast_expr(arg, params))
                .collect::<Vec<_>>()
                .join(", ");
            if let ExprKind::Path(segments) = &callee.kind
                && segments.len() == 1
            {
                match segments[0].as_str() {
                    "some" => return format!("Some({rendered})"),
                    "ok" => return format!("Ok({rendered})"),
                    "err" => return format!("Err({rendered})"),
                    "print" => {
                        return format!("println!(\"{{}}\", crate::__pengu_show(&{rendered}))");
                    }
                    "format" => return format!("crate::__pengu_show(&{rendered})"),
                    _ => {}
                }
            }
            format!("{}({rendered})", lower_ast_expr(callee, params))
        }
        _ => "()".to_owned(),
    }
}

fn ty_rust(ty: &Ty, krate: &HirCrate) -> String {
    match ty {
        Ty::Bool => "bool".to_owned(),
        Ty::Int | Ty::I32 => "i32".to_owned(),
        Ty::I8 => "i8".to_owned(),
        Ty::I16 => "i16".to_owned(),
        Ty::I64 => "i64".to_owned(),
        Ty::Isize => "isize".to_owned(),
        Ty::U8 => "u8".to_owned(),
        Ty::U16 => "u16".to_owned(),
        Ty::U32 => "u32".to_owned(),
        Ty::U64 => "u64".to_owned(),
        Ty::Usize => "usize".to_owned(),
        Ty::Float | Ty::F64 => "f64".to_owned(),
        Ty::F32 => "f32".to_owned(),
        Ty::Char => "char".to_owned(),
        Ty::String => "String".to_owned(),
        Ty::Str => "&str".to_owned(),
        Ty::Unit => "()".to_owned(),
        Ty::Never => "!".to_owned(),
        Ty::Tuple(items) => {
            let items = items
                .iter()
                .map(|item| ty_rust(item, krate))
                .collect::<Vec<_>>();
            if items.len() == 1 {
                format!("({},)", items[0])
            } else {
                format!("({})", items.join(", "))
            }
        }
        Ty::Array(inner, len) => format!("[{}; {len}]", ty_rust(inner, krate)),
        Ty::Slice(inner, mutable) => format!(
            "&{}[{}]",
            if *mutable { "mut " } else { "" },
            ty_rust(inner, krate)
        ),
        Ty::Ref(inner, mutable) => format!(
            "&{}{}",
            if *mutable { "mut " } else { "" },
            ty_rust(inner, krate)
        ),
        Ty::Ptr(inner) => format!("*mut {}", ty_rust(inner, krate)),
        Ty::Vec(inner) => format!("Vec<{}>", ty_rust(inner, krate)),
        Ty::Map(key, value) => format!(
            "::std::collections::HashMap<{}, {}>",
            ty_rust(key, krate),
            ty_rust(value, krate)
        ),
        Ty::Set(inner) => format!("::std::collections::HashSet<{}>", ty_rust(inner, krate)),
        Ty::Option(inner) => format!("Option<{}>", ty_rust(inner, krate)),
        Ty::Result(ok, err) => format!("Result<{}, {}>", ty_rust(ok, krate), ty_rust(err, krate)),
        Ty::Box(inner) => format!("Box<{}>", ty_rust(inner, krate)),
        Ty::Rc(inner) => format!("::std::rc::Rc<{}>", ty_rust(inner, krate)),
        Ty::Arc(inner) => format!("::std::sync::Arc<{}>", ty_rust(inner, krate)),
        Ty::Adt(def, args) => {
            let name = def_path(krate, *def);
            if args.is_empty() {
                name
            } else {
                let args = args
                    .iter()
                    .map(|arg| ty_rust(arg, krate))
                    .collect::<Vec<_>>()
                    .join(", ");
                format!("{name}<{args}>")
            }
        }
        Ty::Generic(def) => rust_ident(&krate.defs[def.index()].name),
        Ty::CStr => "&::std::ffi::CStr".to_owned(),
        Ty::CString => "::std::ffi::CString".to_owned(),
        Ty::Ordering => "::std::cmp::Ordering".to_owned(),
        Ty::Fn(params, ret) => format!(
            "fn({}) -> {}",
            params
                .iter()
                .map(|param| ty_rust(param, krate))
                .collect::<Vec<_>>()
                .join(", "),
            ty_rust(ret, krate)
        ),
        Ty::Range(inner) => format!("::std::ops::Range<{}>", ty_rust(inner, krate)),
        Ty::Iterator(inner) => format!("Box<dyn Iterator<Item = {}>>", ty_rust(inner, krate)),
        Ty::Infer(_) | Ty::IntVar(_) | Ty::FloatVar(_) | Ty::Error => "_".to_owned(),
    }
}

fn ast_type(ty: &Type, krate: &HirCrate, module: pengu_hir::ModuleId) -> String {
    match &ty.kind {
        TypeKind::Unit => "()".to_owned(),
        TypeKind::Option(inner) => format!("Option<{}>", ast_type(inner, krate, module)),
        TypeKind::Ref { mutable, inner } => {
            // `Str` y `CStr` ya son vistas prestadas: `&Str`/`&CStr` no
            // duplican la referencia.
            if !*mutable
                && matches!(&inner.kind, TypeKind::Path { segments, args }
                    if args.is_empty()
                        && segments.last().is_some_and(|name| name == "Str" || name == "CStr"))
            {
                return ast_type(inner, krate, module);
            }
            format!(
                "&{}{}",
                if *mutable { "mut " } else { "" },
                ast_type(inner, krate, module)
            )
        }
        TypeKind::Array { elem, len } => format!(
            "[{}; {}]",
            ast_type(elem, krate, module),
            const_expr(len, krate).unwrap_or_else(|| "0".to_owned())
        ),
        TypeKind::Slice(inner) => format!("[{}]", ast_type(inner, krate, module)),
        TypeKind::Tuple(items) => {
            let items = items
                .iter()
                .map(|item| ast_type(item, krate, module))
                .collect::<Vec<_>>();
            if items.len() == 1 {
                format!("({},)", items[0])
            } else {
                format!("({})", items.join(", "))
            }
        }
        TypeKind::Path { segments, args } => {
            let args = args
                .iter()
                .map(|arg| ast_type(arg, krate, module))
                .collect::<Vec<_>>();
            let joined = args.join(", ");
            if let [name] = segments.as_slice() {
                if let Some(rust) = primitive_type(name) {
                    return rust.to_owned();
                }
                if let Some(def) = lookup_type_def(krate, module, name) {
                    return path_with_args(&def_path(krate, def), &args);
                }
                return match (name.as_str(), args.as_slice()) {
                    ("Vec", [inner]) => format!("Vec<{inner}>"),
                    ("Map", [key, value]) => {
                        format!("::std::collections::HashMap<{key}, {value}>")
                    }
                    ("Set", [inner]) => format!("::std::collections::HashSet<{inner}>"),
                    ("Option", [inner]) => format!("Option<{inner}>"),
                    ("Result", [ok, err]) => format!("Result<{ok}, {err}>"),
                    ("Box", [inner]) => format!("Box<{inner}>"),
                    ("Rc", [inner]) => format!("::std::rc::Rc<{inner}>"),
                    ("Arc", [inner]) => format!("::std::sync::Arc<{inner}>"),
                    _ if args.is_empty() => name.clone(),
                    _ => format!("{name}<{joined}>"),
                };
            }
            let first = segments.first().map(String::as_str);
            let name = match first {
                Some("crate" | "super" | "Self") => segments.join("::"),
                _ => format!("crate::{}", segments.join("::")),
            };
            path_with_args(&name, &args)
        }
        TypeKind::Ptr(inner) => format!("*mut {}", ast_type(inner, krate, module)),
        TypeKind::Fn { params, ret } => format!(
            "fn({}) -> {}",
            params
                .iter()
                .map(|param| ast_type(param, krate, module))
                .collect::<Vec<_>>()
                .join(", "),
            ast_type(ret, krate, module)
        ),
        TypeKind::SelfType => "Self".to_owned(),
    }
}

fn path_with_args(name: &str, args: &[String]) -> String {
    if args.is_empty() {
        name.to_owned()
    } else {
        format!("{name}<{}>", args.join(", "))
    }
}

fn lookup_type_def(krate: &HirCrate, module: pengu_hir::ModuleId, name: &str) -> Option<DefId> {
    let mut scope = Some(krate.module(module).scope);
    while let Some(id) = scope {
        if let Some(binding) = krate.scope(id).types.get(name)
            && let pengu_hir::Res::Def(def) = binding.res
        {
            return Some(def);
        }
        scope = krate.scope(id).parent;
    }
    None
}

fn module_path(krate: &HirCrate, mut module: pengu_hir::ModuleId) -> Vec<String> {
    let mut path = Vec::new();
    while let Some(parent) = krate.module(module).parent {
        path.push(rust_ident(&krate.module(module).name));
        module = parent;
    }
    path.reverse();
    path
}

fn def_path(krate: &HirCrate, def: DefId) -> String {
    let def = krate.def(def);
    let mut path = module_path(krate, def.module);
    path.push(rust_ident(&def.name));
    format!("crate::{}", path.join("::"))
}

fn def_path_named(krate: &HirCrate, def: DefId, name: &str) -> String {
    let def = krate.def(def);
    let mut path = module_path(krate, def.module);
    path.push(rust_ident(name));
    format!("crate::{}", path.join("::"))
}

fn const_expr(expr: &Expr, _krate: &HirCrate) -> Option<String> {
    match &expr.kind {
        ExprKind::Bool(value) => Some(value.to_string()),
        ExprKind::Int(value) => Some(value.clone()),
        ExprKind::Float(value) => Some(value.clone()),
        ExprKind::String(lit) => match lit.parts.as_slice() {
            // `text` es el segmento tal cual aparecía en el fuente, comillas y
            // escapes incluidos: se emite sin volver a escaparlo.
            [pengu_syntax::ast::StringPart::Text(text)] => Some(text.clone()),
            _ => None,
        },
        ExprKind::Char(value) => Some(format!("'{}'", value.escape_default())),
        ExprKind::Array(items) => {
            let items = items
                .iter()
                .map(|item| const_expr(item, _krate))
                .collect::<Option<Vec<_>>>()?;
            Some(format!("[{}]", items.join(", ")))
        }
        ExprKind::ArrayRepeat { value, count } => Some(format!(
            "[{}; {}]",
            const_expr(value, _krate)?,
            const_expr(count, _krate)?
        )),
        ExprKind::Tuple(items) => {
            let items = items
                .iter()
                .map(|item| const_expr(item, _krate))
                .collect::<Option<Vec<_>>>()?;
            Some(if items.len() == 1 {
                format!("({},)", items[0])
            } else {
                format!("({})", items.join(", "))
            })
        }
        ExprKind::Unary { op, expr } => Some(format!(
            "({}{})",
            match op {
                pengu_syntax::ast::UnOp::Neg => "-",
                pengu_syntax::ast::UnOp::Not => "!",
            },
            const_expr(expr, _krate)?
        )),
        ExprKind::Binary { op, lhs, rhs } => Some(format!(
            "({} {} {})",
            const_expr(lhs, _krate)?,
            match op {
                pengu_syntax::ast::BinOp::Add => "+",
                pengu_syntax::ast::BinOp::Sub => "-",
                pengu_syntax::ast::BinOp::Mul => "*",
                pengu_syntax::ast::BinOp::Div => "/",
                pengu_syntax::ast::BinOp::Rem => "%",
                _ => return None,
            },
            const_expr(rhs, _krate)?
        )),
        ExprKind::Path(segments) => Some(segments.join("::")),
        ExprKind::Field { base, name } => {
            let ExprKind::Path(segments) = &base.kind else {
                return None;
            };
            if segments.len() != 1 {
                return None;
            }
            if let Some(rust) = primitive_type(&segments[0]) {
                return Some(format!("{rust}::{name}"));
            }
            let def = _krate
                .assoc_consts
                .get(&segments[0])?
                .iter()
                .copied()
                .find(|def| _krate.def(*def).name == *name)?;
            Some(def_path(_krate, def))
        }
        _ => None,
    }
}

fn primitive_type(name: &str) -> Option<&'static str> {
    Some(match name {
        "Bool" => "bool",
        "Int" => "i32",
        "I8" => "i8",
        "I16" => "i16",
        "I32" => "i32",
        "I64" => "i64",
        "Isize" => "isize",
        "U8" => "u8",
        "U16" => "u16",
        "U32" | "UInt" => "u32",
        "U64" => "u64",
        "Usize" => "usize",
        "Float" | "F64" => "f64",
        "F32" => "f32",
        "Char" => "char",
        "String" => "String",
        "Str" => "&str",
        "Unit" => "()",
        "Never" => "!",
        "CStr" => "&::std::ffi::CStr",
        "CString" => "::std::ffi::CString",
        "Ordering" => "::std::cmp::Ordering",
        _ => return None,
    })
}

fn generics(params: &[GenericParam], krate: &HirCrate) -> String {
    if params.is_empty() {
        return String::new();
    }
    let params = params
        .iter()
        .map(|param| {
            if param.bounds.is_empty() {
                rust_ident(&param.name)
            } else {
                let bounds = param
                    .bounds
                    .iter()
                    .map(|bound| def_path(krate, *bound))
                    .collect::<Vec<_>>()
                    .join(" + ");
                format!("{}: {}", param.name, bounds)
            }
        })
        .collect::<Vec<_>>()
        .join(", ");
    format!("<{params}>")
}

const fn visibility(vis: Visibility) -> &'static str {
    match vis {
        Visibility::Private => "",
        Visibility::Public => "pub ",
        Visibility::Tome => "pub(crate) ",
        Visibility::Scroll => "pub(super) ",
    }
}

fn rust_ident(name: &str) -> String {
    const KEYWORDS: &[&str] = &[
        "as", "break", "const", "continue", "crate", "else", "enum", "extern", "false", "fn",
        "for", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub", "ref",
        "return", "self", "Self", "static", "struct", "super", "trait", "true", "type", "unsafe",
        "use", "where", "while", "async", "await", "dyn",
    ];
    if KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_owned()
    }
}

fn destructure_pattern(
    target: &pengu_lir::DestructureTarget,
    leaves: &mut Vec<pengu_lir::LocalIndex>,
) -> String {
    use pengu_lir::DestructureTarget;
    match target {
        DestructureTarget::Ignore => "_".to_owned(),
        DestructureTarget::Local(local) => {
            let index = leaves.len();
            leaves.push(*local);
            format!("__d{index}")
        }
        DestructureTarget::Tuple(items) => {
            let parts = items
                .iter()
                .map(|item| destructure_pattern(item, leaves))
                .collect::<Vec<_>>()
                .join(", ");
            format!("({parts})")
        }
    }
}

