/// Resultado de codegen.
#[derive(Clone, Debug, Default)]
pub struct Generated {
    /// Fuente Rust generada.
    pub source: String,
    /// Diagnósticos de codegen.
    pub diagnostics: Vec<Diagnostic>,
    /// Mapa aproximado de líneas Rust a spans PenguScript.
    pub sourcemap: SourceMap,
}

/// Mapa aproximado de líneas Rust a spans PenguScript.
#[derive(Clone, Debug, Default, PartialEq, Eq)]
pub struct SourceMap {
    /// Pares (línea generada, span fuente).
    pub entries: Vec<(u32, pengu_span::Span)>,
}

impl SourceMap {
    /// Registra una entrada.
    pub fn push(&mut self, line: u32, span: pengu_span::Span) {
        self.entries.push((line, span));
    }

    /// Extrae entradas de los marcadores `// @pengu-span file:start:end`
    /// emitidos antes de cada sentencia.
    #[must_use]
    pub fn from_markers(source: &str) -> Self {
        let mut map = Self::default();
        let mut pending = None;
        for (index, line) in source.lines().enumerate() {
            let line = line.trim();
            if let Some(rest) = line.strip_prefix("// @pengu-span ") {
                let parts = rest.split(':').collect::<Vec<_>>();
                if parts.len() == 3 {
                    if let (Ok(file), Ok(start), Ok(end)) = (
                        parts[0].parse::<u32>(),
                        parts[1].parse::<u32>(),
                        parts[2].parse::<u32>(),
                    ) {
                        pending = Some(pengu_span::Span::new(
                            pengu_span::FileId::new(file),
                            start,
                            end,
                        ));
                    }
                }
            } else if let Some(span) = pending.take() {
                map.push((index as u32) + 1, span);
            }
        }
        map
    }

    /// Busca el span fuente asociado a una línea Rust (1-based).
    #[must_use]
    pub fn lookup(&self, line: u32) -> Option<pengu_span::Span> {
        self.entries
            .iter()
            .filter(|(candidate, _)| *candidate <= line)
            .max_by_key(|(candidate, _)| *candidate)
            .map(|(_, span)| *span)
    }

    /// Serializa a JSON estable.
    #[must_use]
    pub fn to_json(&self) -> String {
        let entries = self
            .entries
            .iter()
            .map(|(line, span)| {
                format!(
                    "{{\"line\":{line},\"file\":{},\"start\":{},\"end\":{}}}",
                    span.file.index(),
                    span.start,
                    span.end
                )
            })
            .collect::<Vec<_>>()
            .join(",");
        format!("{{\"version\":1,\"entries\":[{entries}]}}")
    }
}

/// Genera un archivo Rust para el crate.
#[must_use]
pub fn generate(krate: &HirCrate, program: &LProgram) -> Generated {
    let mut diagnostics = krate.diagnostics.clone();
    diagnostics.extend(program.diagnostics.iter().cloned());
    if diagnostics.iter().any(Diagnostic::is_error) {
        return Generated {
            source: String::new(),
            diagnostics,
            sourcemap: SourceMap::default(),
        };
    }

    let mut out = String::new();
    out.push_str("// @generated by pengu-codegen B3d\n\n");
    // El código generado usa paréntesis defensivos y el state machine deja brazos
    // divergentes que rustc marca como inalcanzables: son ruido, no defectos.
    out.push_str(
        "#![allow(dead_code, unused_parens, unreachable_code, unused_variables, unused_mut, non_snake_case, non_camel_case_types, suspicious_double_ref_op, unused_assignments, unused_imports)]\n\n",
    );
    out.push_str(RUNTIME);
    out.push_str("mod __pengu_std {\n");
    for line in STD_RT.lines() {
        if line.is_empty() {
            out.push('\n');
        } else {
            let _ = writeln!(out, "    {line}");
        }
    }
    out.push_str("}\n\n");
    let mut sourcemap = SourceMap::default();
    emit_module(&mut out, krate, program, krate.root, &mut sourcemap);
    sourcemap
        .entries
        .extend(SourceMap::from_markers(&out).entries);
    Generated {
        source: out,
        diagnostics,
        sourcemap,
    }
}

fn emit_module(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    module_id: pengu_hir::ModuleId,
    sourcemap: &mut SourceMap,
) {
    let module = krate.module(module_id);
    let mut items = module.items.clone();
    items.sort_by_key(|def| def.index());
    for def_id in items {
        sourcemap.push((out.lines().count() + 1) as u32, krate.def(def_id).span);
        emit_item(out, krate, program, def_id);
    }
    emit_foreign(out, krate, module_id);
    for imp in &krate.impls {
        if imp.module == module_id {
            emit_impl(out, krate, program, imp);
        }
    }
    // Constantes asociadas (`Int.MAX`): se emiten como `const` del módulo dueño
    // y se referencian por `def_path`.
    for imp in &krate.impls {
        if imp.module != module_id {
            continue;
        }
        for def in &imp.consts {
            if let Some(constant) = krate.consts.get(def) {
                emit_const(out, krate, constant);
                out.push('\n');
            }
        }
    }

    let mut children: Vec<_> = krate
        .modules
        .iter()
        .filter(|child| child.parent == Some(module_id))
        .collect();
    children.sort_by_key(|child| child.name.clone());
    for child in children {
        let vis = if krate.is_std_module(child.id) {
            "pub "
        } else {
            child
                .def
                .map(|def| visibility(krate.def(def).vis))
                .unwrap_or_default()
        };
        let _ = writeln!(out, "{vis}mod {} {{", rust_ident(&child.name));
        let mut inner = String::new();
        emit_module(&mut inner, krate, program, child.id, sourcemap);
        for line in inner.lines() {
            if line.is_empty() {
                out.push('\n');
            } else {
                let _ = writeln!(out, "    {line}");
            }
        }
        out.push_str("}\n\n");
    }
}

fn emit_item(out: &mut String, krate: &HirCrate, program: &LProgram, def_id: DefId) {
    let def = krate.def(def_id);
    match def.kind {
        pengu_hir::DefKind::Type => {
            if let Some(adt) = krate.adt(def_id) {
                emit_adt(out, krate, adt);
                out.push('\n');
            } else if let Some(ty) = krate.aliases.get(&def_id) {
                let _ = writeln!(
                    out,
                    "{}type {} = {};",
                    visibility(def.vis),
                    rust_ident(&def.name),
                    ast_type(ty, krate, def.module)
                );
                out.push('\n');
            }
        }
        pengu_hir::DefKind::Pact => {
            if let Some(pact) = krate.pacts.get(&def_id) {
                emit_pact(out, krate, program, pact);
                out.push('\n');
            }
        }
        pengu_hir::DefKind::Function => {
            if krate.foreign_fns.contains(&def_id) || method_defs(krate).contains(&def_id) {
                return;
            }
            let functions: Vec<_> = program
                .functions
                .iter()
                .filter(|function| function.def == def_id)
                .collect();
            if functions.is_empty() {
                return;
            }
            for function in functions {
                if let Some(info) = krate.tests.get(&def_id) {
                    emit_test(out, krate, program, def, function, info);
                } else if krate.grimoires.contains(&def_id) {
                    emit_grimoire(out, krate, program, function);
                } else {
                    emit_function(out, krate, program, def, function);
                }
            }
            out.push('\n');
        }
        pengu_hir::DefKind::Const | pengu_hir::DefKind::Static => {
            if let Some(constant) = krate.consts.get(&def_id) {
                emit_const(out, krate, constant);
                out.push('\n');
            }
        }
        _ => {}
    }
}

fn emit_test(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    def: &pengu_hir::Def,
    function: &LFunction,
    info: &pengu_hir::TestInfo,
) {
    out.push_str("#[test]\n");
    if let Some(message) = &info.should_panic {
        if message.is_empty() {
            out.push_str("#[should_panic]\n");
        } else {
            let _ = writeln!(out, "#[should_panic(expected = {message:?})]");
        }
    }
    if let Some(message) = &info.ignore {
        if message.is_empty() {
            out.push_str("#[ignore]\n");
        } else {
            let _ = writeln!(out, "#[ignore = {message:?}]");
        }
    }
    let header = format!("fn {}() {{", rust_ident(&def.name));
    emit_function_body(out, krate, program, function, &header);
}

fn emit_grimoire(out: &mut String, krate: &HirCrate, program: &LProgram, function: &LFunction) {
    let ret = if function.ret == Ty::Unit {
        String::new()
    } else {
        format!(
            " -> {}",
            ty_rust(&function.ret, krate).replace("&str", "&'static str")
        )
    };
    let header = format!("fn main(){ret} {{");
    emit_function_body(out, krate, program, function, &header);
}

fn emit_function(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    def: &pengu_hir::Def,
    function: &LFunction,
) {
    let params = function
        .params
        .iter()
        .map(|param| {
            format!(
                "mut {}: {}",
                rust_ident(&param.name),
                ty_rust(&param.ty, krate)
            )
        })
        .collect::<Vec<_>>()
        .join(", ");
    let ret_ty = if function.ret == Ty::Unit {
        String::new()
    } else {
        format!(" -> {}", ty_rust(&function.ret, krate))
    };
    let unsafety = if krate.curse_fns.contains(&def.id) {
        "unsafe "
    } else {
        ""
    };
    let header = format!(
        "{}{unsafety}fn {}({params}){ret_ty} {{",
        visibility(def.vis),
        rust_ident(&function.name)
    );
    emit_function_body(out, krate, program, function, &header);
}

fn method_defs(krate: &HirCrate) -> std::collections::HashSet<DefId> {
    let mut defs = std::collections::HashSet::new();
    for pact in krate.pacts.values() {
        defs.extend(pact.methods.iter().copied());
    }
    for imp in &krate.impls {
        defs.extend(imp.methods.iter().copied());
    }
    defs
}

fn emit_adt(out: &mut String, krate: &HirCrate, adt: &AdtDef) {
    let def = &krate.defs[adt.def.index()];
    let mut derives = adt.derives.clone();
    if !derives.iter().any(|derive| derive == "Clone") && adt_clone_ok(krate, adt) {
        derives.push("Clone".to_owned());
    }
    if !derives.is_empty() {
        let _ = writeln!(out, "#[derive({})]", derives.join(", "));
    }
    // Layout determinista: sin `repr` Rust reordena campos y optimiza enums con
    // nichos, y los tamaños dejarían de ser calculables desde Pengu
    // (ver `pengu-layout`).
    match adt.kind {
        AdtKind::Record => out.push_str("#[repr(C)]\n"),
        AdtKind::Sum => {
            // `repr(C, u32)` no se admite en enums sin payload: ahí el
            // discriminante es todo el valor.
            let fieldless = adt.variants.iter().all(|variant| variant.fields.is_empty());
            out.push_str(if fieldless {
                "#[repr(u32)]\n"
            } else {
                "#[repr(C, u32)]\n"
            });
        }
    }
    let generics = generics(&adt.generics, krate);
    match adt.kind {
        AdtKind::Record => emit_record(out, krate, def, adt, &generics),
        AdtKind::Sum => emit_sum(out, krate, def, adt, &generics),
    }
}

/// Tipos cuyos valores se pueden copiar con `Clone` en el backend.
///
/// Los runes se derivan de forma conservadora: si algún campo no es copiable
/// no se deriva `Clone` y el tipo conserva su semántica de movimiento.
fn adt_clone_ok(krate: &HirCrate, adt: &AdtDef) -> bool {
    adt_clone_ok_at(krate, adt, 0)
}

/// `depth` corta la recursión de los tipos recursivos (`Json` contiene
/// `Vec[Json]`): al llegar al límite se asume que el campo es clonable, que es
/// la apuesta segura porque un ADT recursivo siempre indirecciona por `Vec`,
/// `Box` u `Option`.
fn adt_clone_ok_at(krate: &HirCrate, adt: &AdtDef, depth: u32) -> bool {
    if depth > 8 {
        return true;
    }
    adt.fields
        .iter()
        .all(|field| type_clone_ok_at(krate, &field.ty, depth + 1))
        && adt
            .variants
            .iter()
            .flat_map(|variant| variant.fields.iter())
            .all(|field| type_clone_ok_at(krate, &field.ty, depth + 1))
}

fn type_clone_ok_at(krate: &HirCrate, ty: &pengu_syntax::ast::Type, depth: u32) -> bool {
    if depth > 12 {
        return true;
    }
    match &ty.kind {
        TypeKind::Unit | TypeKind::SelfType => true,
        TypeKind::Option(inner) | TypeKind::Slice(inner) | TypeKind::Ptr(inner) => {
            type_clone_ok_at(krate, inner, depth + 1)
        }
        TypeKind::Ref { inner, .. } => type_clone_ok_at(krate, inner, depth + 1),
        TypeKind::Array { elem, .. } => type_clone_ok_at(krate, elem, depth + 1),
        TypeKind::Tuple(items) => items
            .iter()
            .all(|item| type_clone_ok_at(krate, item, depth + 1)),
        TypeKind::Fn { .. } => false,
        TypeKind::Path { segments, args } => {
            let name = segments.last().map(String::as_str).unwrap_or("");
            if args
                .iter()
                .all(|arg| type_clone_ok_at(krate, arg, depth + 1))
            {
                if matches!(
                    name,
                    "Vec"
                        | "Map"
                        | "Set"
                        | "Option"
                        | "Result"
                        | "Box"
                        | "Rc"
                        | "Arc"
                        | "CStr"
                        | "CString"
                        | "String"
                        | "Str"
                        | "Range"
                        | "Ordering"
                ) || primitive_type(name).is_some()
                {
                    return true;
                }
                if let Some(def) = krate
                    .defs
                    .iter()
                    .find(|def| def.name == name && def.kind == pengu_hir::DefKind::Type)
                {
                    if let Some(adt) = krate.adt(def.id) {
                        return adt_clone_ok_at(krate, adt, depth + 1);
                    }
                }
                return false;
            }
            false
        }
    }
}

fn emit_record(
    out: &mut String,
    krate: &HirCrate,
    def: &pengu_hir::Def,
    adt: &AdtDef,
    generics: &str,
) {
    let name = rust_ident(&def.name);
    if adt.fields.is_empty() {
        let _ = writeln!(out, "{}struct {name}{generics};", visibility(def.vis));
        return;
    }
    let tuple = adt
        .fields
        .iter()
        .all(|field| field.name.parse::<usize>().is_ok());
    if tuple {
        let fields = adt
            .fields
            .iter()
            .map(|field| {
                format!(
                    "{}{}",
                    visibility(field.vis),
                    ast_type(&field.ty, krate, adt.module)
                )
            })
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(
            out,
            "{}struct {name}{generics}({fields});",
            visibility(def.vis)
        );
        return;
    }
    let _ = writeln!(out, "{}struct {name}{generics} {{", visibility(def.vis));
    for field in &adt.fields {
        let _ = writeln!(
            out,
            "    {}{}: {},",
            visibility(field.vis),
            field.name,
            ast_type(&field.ty, krate, adt.module)
        );
    }
    out.push_str("}\n");
}

fn emit_sum(
    out: &mut String,
    krate: &HirCrate,
    def: &pengu_hir::Def,
    adt: &AdtDef,
    generics: &str,
) {
    let name = rust_ident(&def.name);
    let _ = writeln!(out, "{}enum {name}{generics} {{", visibility(def.vis));
    for variant in &adt.variants {
        emit_variant(out, krate, variant, adt.module);
    }
    out.push_str("}\n");
}

fn emit_variant(
    out: &mut String,
    krate: &HirCrate,
    variant: &AdtVariant,
    module: pengu_hir::ModuleId,
) {
    if variant.fields.is_empty() {
        let _ = writeln!(out, "    {},", rust_ident(&variant.name));
    } else if variant.tuple {
        let fields = variant
            .fields
            .iter()
            .map(|field| ast_type(&field.ty, krate, module))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(out, "    {}({fields}),", rust_ident(&variant.name));
    } else {
        let _ = writeln!(out, "    {} {{", rust_ident(&variant.name));
        for field in &variant.fields {
            let _ = writeln!(
                out,
                "        {}: {},",
                rust_ident(&field.name),
                ast_type(&field.ty, krate, module)
            );
        }
        out.push_str("    },\n");
    }
}

fn emit_foreign(out: &mut String, krate: &HirCrate, module: pengu_hir::ModuleId) {
    let mut by_abi: std::collections::BTreeMap<String, Vec<DefId>> =
        std::collections::BTreeMap::new();
    for def in &krate.foreign_fns {
        if krate.def(*def).module == module {
            let abi = krate
                .foreign_abis
                .get(def)
                .cloned()
                .unwrap_or_else(|| "C".to_owned());
            by_abi.entry(abi).or_default().push(*def);
        }
    }
    for (abi, mut defs) in by_abi {
        if abi == "pengu" {
            continue;
        }
        defs.sort_by_key(|def| def.index());
        let _ = writeln!(out, "unsafe extern {abi:?} {{");
        for def in defs {
            let Some(signature) = krate.signatures.get(&def) else {
                continue;
            };
            let params = signature
                .params
                .iter()
                .enumerate()
                .map(|(i, ty)| format!("p{i}: {}", foreign_type(ty, krate, module)))
                .collect::<Vec<_>>()
                .join(", ");
            let ret = foreign_type(&signature.ret, krate, module);
            let name = rust_ident(&krate.defs[def.index()].name);
            let _ = writeln!(out, "    pub fn {name}({params}) -> {ret};");
        }
        out.push_str("}\n\n");
    }
}

/// Un `const char *` devuelto por C no se puede prestar de ningún argumento:
/// el contrato de `foreign` es que la cadena sobrevive a la llamada.
fn ast_is_cstr(ty: &pengu_syntax::ast::Type) -> bool {
    match &ty.kind {
        pengu_syntax::ast::TypeKind::Path { segments, .. } => {
            segments.last().is_some_and(|name| name == "CStr")
        }
        pengu_syntax::ast::TypeKind::Ref { inner, .. } => ast_is_cstr(inner),
        _ => false,
    }
}

/// `CStr` es *unsized*: en la frontera C viaja como puntero simple, nunca como
/// referencia gorda.
fn foreign_type(
    ty: &pengu_syntax::ast::Type,
    krate: &HirCrate,
    module: pengu_hir::ModuleId,
) -> String {
    if ast_is_cstr(ty) {
        "*const ::std::os::raw::c_char".to_owned()
    } else {
        ast_type(ty, krate, module)
    }
}

fn emit_const(out: &mut String, krate: &HirCrate, constant: &ConstDef) {
    let def = &krate.defs[constant.def.index()];
    let value = constant
        .value
        .as_ref()
        .and_then(|expr| const_expr(expr, krate))
        .unwrap_or_else(|| "Default::default()".to_owned());
    let keyword = if def.kind == pengu_hir::DefKind::Static {
        "static"
    } else {
        "const"
    };
    let _ = writeln!(
        out,
        "{}{keyword} {}: {} = {value};",
        visibility(def.vis),
        rust_ident(&def.name),
        ast_type(&constant.ty, krate, constant.module)
    );
}

fn emit_pact(out: &mut String, krate: &HirCrate, program: &LProgram, pact: &PactDef) {
    let def = &krate.defs[pact.def.index()];
    // `Show` is the synthetic prelude pact; the runtime already defines it.
    if def.name == "Show" {
        return;
    }
    let supertrait = pact
        .superpact
        .map(|superpact| format!(": {}", def_path(krate, superpact)))
        .unwrap_or_default();
    let generics = generics(&pact.generics, krate);
    let _ = writeln!(
        out,
        "{}trait {}{generics}{supertrait} {{",
        visibility(def.vis),
        rust_ident(&def.name)
    );
    for method in &pact.methods {
        let Some(signature) = krate.signatures.get(method) else {
            continue;
        };
        let name = rust_ident(&krate.defs[method.index()].name);
        let receiver = signature.receiver.map_or("", |receiver| match receiver {
            Receiver::Ref => "&self, ",
            Receiver::Mut => "&mut self, ",
            Receiver::Own => "self, ",
        });
        let params = signature
            .params
            .iter()
            .enumerate()
            .map(|(i, ty)| format!("p{i}: {}", ast_type(ty, krate, pact.module)))
            .collect::<Vec<_>>()
            .join(", ");
        let params = if params.is_empty() {
            receiver.trim_end_matches(", ").to_owned()
        } else {
            format!("{receiver}{params}")
        };
        let ret = ast_type(&signature.ret, krate, pact.module);
        if let Some(function) = program.functions.iter().find(|f| f.def == *method) {
            let header = format!("    fn {name}({params}) -> {ret} {{");
            let mut body = String::new();
            emit_function_body(&mut body, krate, program, function, &header);
            for line in body.lines() {
                let _ = writeln!(out, "{line}");
            }
        } else {
            let _ = writeln!(out, "    fn {name}({params}) -> {ret};");
        }
    }
    out.push_str("}\n");
}

fn emit_impl(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    imp: &pengu_hir::hir::ImplDef,
) {
    if imp.methods.is_empty() {
        return;
    }
    // Los tipos integrados (`Vec`, `Map`, `Set`, ...) no admiten `impl`
    // inherente: sus métodos son paso directo al método nativo de Rust.
    if builtin_impl_label(&imp.ty).is_some() {
        return;
    }
    let primitive = imp.methods.iter().any(|method| {
        program
            .functions
            .iter()
            .filter(|function| function.def == *method)
            .any(|function| function_self_ty(krate, function).is_some_and(|ty| is_primitive(&ty)))
    });
    if primitive {
        for method in &imp.methods {
            if let Some(function) = program
                .functions
                .iter()
                .find(|function| function.def == *method)
            {
                emit_primitive_method(out, krate, program, function, Some(&imp.ty));
            }
        }
        return;
    }
    let pact_name = imp.pact.map(|pact| def_path(krate, pact));
    if imp.generics.is_empty() {
        let target = ast_type(&imp.ty, krate, imp.module);
        let generics = generics(&imp.generics, krate);
        emit_impl_header(out, pact_name.as_deref(), &format!("{generics}{target}"));
        for method in &imp.methods {
            if let Some(function) = program
                .functions
                .iter()
                .find(|function| function.def == *method)
            {
                emit_impl_method(out, krate, program, function, pact_name.is_none());
            }
        }
        out.push_str("}\n");
        return;
    }

    let mut groups: Vec<(Ty, Vec<&LFunction>)> = Vec::new();
    for method in &imp.methods {
        for function in program
            .functions
            .iter()
            .filter(|function| function.def == *method)
        {
            let Some(self_ty) = function_self_ty(krate, function) else {
                continue;
            };
            // Un `self_ty` que aún menciona parámetros genéricos es el cuerpo
            // plantilla del ritual: Rust no admite un `enum` de estado interno
            // con parámetros del `impl` externo, así que se omite y se emiten
            // las instancias monomorfizadas (más abajo).
            if ty_mentions_generic(&self_ty) {
                continue;
            }
            if let Some((_, functions)) = groups.iter_mut().find(|(ty, _)| *ty == self_ty) {
                functions.push(function);
            } else {
                groups.push((self_ty, vec![function]));
            }
        }
    }
    for (self_ty, functions) in groups {
        let target = ty_rust(&self_ty, krate);
        emit_impl_header(out, pact_name.as_deref(), &target);
        for method in &imp.methods {
            // Las funciones asociadas de un `ritual` genérico se omiten: Rust no
            // permite dos `new` en impls distintos y el llamador no puede
            // desambiguar; se ofrecen como funciones libres (N62).
            let associated = krate
                .signature(*method)
                .is_some_and(|signature| signature.receiver.is_none());
            if associated {
                continue;
            }
            if let Some(function) = functions.iter().find(|function| function.def == *method) {
                emit_impl_method(out, krate, program, function, pact_name.is_none());
            }
        }
        out.push_str("}\n");
    }
}

/// Emite un método inherente de un primitivo como función libre.
///
/// Rust no permite `impl i32 { ... }`, así que el receptor pasa a ser un
/// parámetro normal (`__self`) y las llamadas se reescriben a la ruta de la
/// función (D3 de `scratch/STDLIB_PLAN.md`).
fn emit_primitive_method(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
    fallback_ty: Option<&pengu_syntax::ast::Type>,
) {
    let _ = fallback_ty;
    let self_ty = function_self_ty(krate, function);
    let name = primitive_fn_name(krate, function.def);
    let has_receiver = krate
        .signature(function.def)
        .is_some_and(|signature| signature.receiver.is_some());
    let mut params = Vec::new();
    let mut lifetime = None;
    if has_receiver {
        let Some(self_ty) = self_ty else {
            return;
        };
        // `String` no es `Copy`: el receptor se pasa por referencia.
        let ty = ty_rust(&self_ty, krate);
        let receiver = krate
            .signature(function.def)
            .and_then(|signature| signature.receiver);
        params.push(match receiver {
            Some(pengu_syntax::ast::Receiver::Mut) => format!("__self: &mut {ty}"),
            Some(pengu_syntax::ast::Receiver::Own) => format!("__self: {ty}"),
            _ if primitive_is_copy(krate, function.def) => format!("__self: {ty}"),
            _ => format!("__self: &{ty}"),
        });
    }
    params.extend(
        function
            .params
            .iter()
            .map(|param| format!("{}: {}", rust_ident(&param.name), ty_rust(&param.ty, krate))),
    );
    let ret_ty = if function.ret == Ty::Unit {
        String::new()
    } else {
        format!(" -> {}", ty_rust(&function.ret, krate))
    };
    // Un método que devuelve `Str` prestado necesita ligar la vida del
    // receptor: `fn trim<'a>(__self: &'a str) -> &'a str`.
    if ret_ty.contains("&str") {
        lifetime = Some("'a");
        for param in &mut params {
            if param.starts_with("__self: &") {
                *param = param.replace("__self: &", "__self: &'a ");
            }
        }
    }
    let ret_ty = match lifetime {
        Some(lifetime) => ret_ty.replace("&str", &format!("&{lifetime} str")),
        None => ret_ty,
    };
    let generics = match lifetime {
        Some(lifetime) => format!("<{lifetime}>"),
        None => String::new(),
    };
    let header = format!("pub fn {name}{generics}({}){ret_ty} {{", params.join(", "));
    emit_function_body(out, krate, program, function, &header);
}

fn emit_impl_header(out: &mut String, pact: Option<&str>, target: &str) {
    match pact {
        Some(pact) => {
            let _ = writeln!(out, "impl {pact} for {target} {{");
        }
        None => {
            let _ = writeln!(out, "impl {target} {{");
        }
    }
}

fn emit_impl_method(
    out: &mut String,
    krate: &HirCrate,
    program: &LProgram,
    function: &LFunction,
    inherent: bool,
) {
    let Some(signature) = krate.signatures.get(&function.def) else {
        return;
    };
    let name = rust_ident(&krate.defs[function.def.index()].name);
    let receiver = signature
        .receiver
        .map_or(String::new(), |receiver| match receiver {
            Receiver::Ref => "&self, ".to_owned(),
            Receiver::Mut => "&mut self, ".to_owned(),
            Receiver::Own => "self, ".to_owned(),
        });
    let params = function
        .params
        .iter()
        .map(|param| format!("{}: {}", rust_ident(&param.name), ty_rust(&param.ty, krate)))
        .collect::<Vec<_>>()
        .join(", ");
    let params = if params.is_empty() {
        receiver.trim_end_matches(", ").to_owned()
    } else {
        format!("{receiver}{params}")
    };
    let ret_ty = if function.ret == Ty::Unit {
        String::new()
    } else {
        format!(" -> {}", ty_rust(&function.ret, krate))
    };
    // Los métodos de un pacto comparten la visibilidad del pacto: `pub` dentro
    // de un `impl Trait for T` es E0449.
    let visibility = if inherent { "pub " } else { "" };
    let header = format!("    {visibility}fn {name}({params}){ret_ty} {{");
    emit_function_body(out, krate, program, function, &header);
}

fn function_self_ty(krate: &HirCrate, function: &LFunction) -> Option<Ty> {
    let body = krate
        .bodies
        .iter()
        .find(|body| body.owner == function.def)?;
    let self_local = body.self_local?;
    function
        .locals
        .iter()
        .find(|local| local.id == self_local.index())
        .map(|local| local.ty.clone())
}

/// Tipos primitivos: sus métodos inherentes no pueden emitirse como `impl`.
fn is_primitive(ty: &Ty) -> bool {
    matches!(
        ty,
        Ty::Bool
            | Ty::Int
            | Ty::I8
            | Ty::I16
            | Ty::I32
            | Ty::I64
            | Ty::Isize
            | Ty::U8
            | Ty::U16
            | Ty::U32
            | Ty::U64
            | Ty::Usize
            | Ty::Float
            | Ty::F32
            | Ty::F64
            | Ty::Char
            | Ty::String
            | Ty::Str
    )
}

/// ¿El método pertenece a un `ritual` sobre un primitivo?
/// Etiqueta corta del tipo primitivo dueño de un método inherente.
fn primitive_label(krate: &HirCrate, def: DefId) -> Option<&'static str> {
    let imp = krate.impls.iter().find(|imp| imp.methods.contains(&def))?;
    let pengu_syntax::ast::TypeKind::Path { segments, .. } = &imp.ty.kind else {
        return None;
    };
    match segments.last()?.as_str() {
        "Bool" => Some("bool"),
        "Int" | "I32" => Some("int"),
        "I8" => Some("i8"),
        "I16" => Some("i16"),
        "I64" => Some("i64"),
        "Isize" => Some("isize"),
        "U8" => Some("u8"),
        "U16" => Some("u16"),
        "U32" => Some("u32"),
        "U64" => Some("u64"),
        "Usize" => Some("usize"),
        "Float" | "F64" => Some("float"),
        "F32" => Some("f32"),
        "Char" => Some("char"),
        "Str" => Some("str"),
        "String" => Some("string"),
        _ => None,
    }
}

/// Nombre en Rust de un método inherente de un primitivo. Los métodos de
/// `Str` y `String` comparten módulo, así que se prefijan con el tipo.
fn primitive_fn_name(krate: &HirCrate, def: DefId) -> String {
    let name = rust_ident(&krate.defs[def.index()].name);
    match primitive_label(krate, def) {
        Some(label) => format!("{label}__{name}"),
        None => name,
    }
}

/// `true` salvo para `String`, que no es `Copy`.
fn primitive_is_copy(krate: &HirCrate, def: DefId) -> bool {
    primitive_label(krate, def) != Some("string")
}

/// Nombre Rust del tipo integrado si `ty` es uno de ellos (`Vec[T]` → `Vec`).
fn builtin_impl_label(ty: &pengu_syntax::ast::Type) -> Option<&'static str> {
    let pengu_syntax::ast::TypeKind::Path { segments, .. } = &ty.kind else {
        return None;
    };
    match segments.last().map(String::as_str)? {
        "Vec" => Some("Vec"),
        "Iter" => Some("Iter"),
        "Map" => Some("HashMap"),
        "Set" => Some("HashSet"),
        "Option" => Some("Option"),
        "Result" => Some("Result"),
        "Box" => Some("Box"),
        "Rc" => Some("Rc"),
        "Arc" => Some("Arc"),
        _ => None,
    }
}

/// Ruta Rust del tipo integrado al que pertenece `def`, si sus métodos son
/// paso directo a Rust (`Vec.new` → `std::vec::Vec::new`).
fn associated_builtin_path(krate: &HirCrate, def: DefId) -> Option<&'static str> {
    match builtin_label(krate, def)? {
        "Vec" => Some("std::vec::Vec"),
        "HashMap" => Some("std::collections::HashMap"),
        "HashSet" => Some("std::collections::HashSet"),
        "Option" => Some("std::option::Option"),
        "Result" => Some("std::result::Result"),
        "Box" => Some("std::boxed::Box"),
        "Rc" => Some("std::rc::Rc"),
        "Arc" => Some("std::sync::Arc"),
        _ => None,
    }
}

/// Tipo de destino de un `ritual` inherente sobre un `rune` o una suma.
///
/// Las funciones asociadas de estos tipos se emiten dentro de su `impl`, así
/// que la llamada debe resolverse como `Tipo::funcion` y no como ruta de
/// módulo.
/// `true` si el tipo menciona un parámetro genérico (`T`, `K`, ...).
fn ty_mentions_generic(ty: &Ty) -> bool {
    match ty {
        Ty::Generic(_) => true,
        Ty::Adt(_, args) => args.iter().any(ty_mentions_generic),
        Ty::Vec(inner)
        | Ty::Set(inner)
        | Ty::Option(inner)
        | Ty::Box(inner)
        | Ty::Rc(inner)
        | Ty::Arc(inner)
        | Ty::Ref(inner, _)
        | Ty::Slice(inner, _)
        | Ty::Ptr(inner)
        | Ty::Array(inner, _)
        | Ty::Range(inner)
        | Ty::Iterator(inner) => ty_mentions_generic(inner),
        Ty::Map(key, value) | Ty::Result(key, value) => {
            ty_mentions_generic(key) || ty_mentions_generic(value)
        }
        Ty::Tuple(items) | Ty::Fn(items, _) => items.iter().any(ty_mentions_generic),
        _ => false,
    }
}

fn inherent_impl_target(
    krate: &HirCrate,
    program: &LProgram,
    def: DefId,
    type_args: &[Ty],
) -> Option<String> {
    let imp = krate.impls.iter().find(|imp| imp.methods.contains(&def))?;
    if imp.pact.is_some() || builtin_impl_label(&imp.ty).is_some() || !imp.generics.is_empty() {
        return None;
    }
    let target = ast_type(&imp.ty, krate, imp.module);
    if imp.generics.is_empty() {
        return Some(target);
    }
    if !type_args.is_empty() && type_args.len() == imp.generics.len() {
        let bare = match target.split_once('<') {
            Some((head, _)) => head.to_owned(),
            None => target,
        };
        let args = type_args
            .iter()
            .map(|ty| ty_rust(ty, krate))
            .collect::<Vec<_>>()
            .join(", ");
        return Some(format!("{bare}::<{args}>"));
    }
    // Impl genérico: si la instancia ya está monomorfizada, se llama con
    // turbofish (`Tipo::<i32>::new`), que es lo único que evita la ambigüedad
    // cuando hay varias instancias con el mismo nombre de función.
    let concrete = program
        .functions
        .iter()
        .filter(|function| function.def == def)
        .filter_map(|function| function_self_ty(krate, function))
        .find(|ty| !ty_mentions_generic(ty));
    Some(match concrete {
        Some(ty) => match ty_rust(&ty, krate).split_once('<') {
            Some((head, args)) => format!("{head}::<{args}"),
            None => ty_rust(&ty, krate),
        },
        None => match target.split_once('<') {
            Some((head, _)) => head.to_owned(),
            None => target,
        },
    })
}

/// Etiqueta del tipo integrado al que pertenece `def`, si sus métodos son
/// paso directo a Rust.
fn builtin_label(krate: &HirCrate, def: DefId) -> Option<&'static str> {
    krate
        .impls
        .iter()
        .find(|imp| imp.methods.contains(&def))
        .and_then(|imp| builtin_impl_label(&imp.ty))
}

/// Renderiza los argumentos de un método integrado anteponiendo `&` a los que
/// el método nativo de Rust recibe por referencia (`contains`, `binary_search`).
fn builtin_args(krate: &HirCrate, def: DefId, rendered: &[String]) -> String {
    let params = krate
        .signature(def)
        .map(|signature| signature.params.clone())
        .unwrap_or_default();
    rendered
        .iter()
        .enumerate()
        .map(|(index, arg)| match params.get(index) {
            Some(ty) if matches!(ty.kind, pengu_syntax::ast::TypeKind::Ref { .. }) => {
                format!("&{arg}")
            }
            _ => arg.clone(),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

