#!/usr/bin/env bash
# Measure the size fixtures and compare them against tests/baseline/sizes.json.
#
# Usage:
#   tools/size_report.sh            # check (CI)
#   tools/size_report.sh --update   # rewrite the baseline (maintainers)
#
# The fixtures live in tests/size/. They are built exactly like a release
# program: --profile release --prune-native (the linker adds --gc-sections and
# strips symbols). A fixture may grow at most 10% or 2 KiB over its baseline,
# whichever is larger, to absorb compiler/OS differences.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
PSC="${PSC:-$ROOT/build/psc}"
BASELINE="$ROOT/tests/baseline/sizes.json"
UPDATE=0
[ "${1:-}" = "--update" ] && UPDATE=1

if [ ! -x "$PSC" ]; then
  echo "size_report: no psc at $PSC (set PSC=... or run tools/build.sh)" >&2
  exit 1
fi

FIXTURES=(hello json toml yaml regex compressus chronicle)
OUT="$(mktemp -d "${TMPDIR:-/tmp}/pengu-size.XXXXXX")"
trap 'rm -rf "$OUT"' EXIT
RESULTS="$OUT/results.tsv"
: > "$RESULTS"

# A minimal project manifest: the fixture is built outside the repository, so
# it needs the release profile explicitly (otherwise the compiler uses -O0 and
# the measurement is meaningless). It deliberately declares no satellite links.
cat > "$OUT/pengu.toml" <<'TOML'
[project]
name = "size-fixture"
version = "0.0.0"
entry = "hello.pengu"
output = "exe"

[build]
links = ["pengu_runtime"]
cflags = ["-Wall", "-std=c11"]
cc = "gcc"

[profiles.release]
cflags = ["-O3", "-DNDEBUG", "-ffunction-sections", "-fdata-sections"]
defines = ["NDEBUG"]
TOML

for name in "${FIXTURES[@]}"; do
  src="$ROOT/tests/size/$name.pengu"
  [ -f "$src" ] || { echo "size_report: missing fixture $src" >&2; exit 1; }
  # Build from a temporary project root: otherwise the repo's pengu.toml
  # contributes its own links and the measurement stops being comparable.
  cp "$src" "$OUT/$name.pengu"
  if ! (cd "$OUT" && "$PSC" build "$name.pengu" --exe --profile release --no-cache \
      --prune-native --out "$OUT/$name") >"$OUT/$name.log" 2>&1; then
    echo "size_report: failed to build $name" >&2
    cat "$OUT/$name.log" >&2
    exit 1
  fi
  printf '%s\t%s\n' "$name" "$(wc -c < "$OUT/$name" | tr -d ' ')" >> "$RESULTS"
done

if [ "$UPDATE" -eq 1 ]; then
  python3 - "$BASELINE" "$RESULTS" <<'PY'
import json
import sys
from pathlib import Path

baseline, results = sys.argv[1], sys.argv[2]
data = {
    "format": 1,
    "note": "release + --prune-native + -s; generated by tools/size_report.sh --update",
    "fixtures": {},
}
for line in Path(results).read_text().splitlines():
    if not line.strip():
        continue
    name, size = line.split("\t")
    data["fixtures"][name] = int(size)
Path(baseline).parent.mkdir(parents=True, exist_ok=True)
Path(baseline).write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
print(f"size_report: wrote {baseline} ({len(data['fixtures'])} fixtures)")
PY
  exit 0
fi

if [ ! -f "$BASELINE" ]; then
  echo "size_report: no baseline at $BASELINE" >&2
  echo "size_report: run 'tools/size_report.sh --update' on the reference platform" >&2
  exit 0
fi

python3 - "$BASELINE" "$RESULTS" <<'PY'
import json
import sys
from pathlib import Path

baseline_path, results_path = sys.argv[1], sys.argv[2]
base = json.loads(Path(baseline_path).read_text())["fixtures"]
rows = []
for line in Path(results_path).read_text().splitlines():
    if not line.strip():
        continue
    name, size = line.split("\t")
    rows.append((name, int(size)))

failed = []
print(f"{'fixture':<12} {'bytes':>8} {'baseline':>9} {'delta':>8}  budget")
for name, size in rows:
    old = base.get(name)
    if old is None:
        print(f"{name:<12} {size:>8} {'-':>9} {'-':>8}  (no baseline)")
        continue
    budget = max(old + 2048, int(old * 1.10))
    delta = size - old
    flag = "OK" if size <= budget else "OVER"
    if size > budget:
        failed.append((name, size, old, budget))
    print(f"{name:<12} {size:>8} {old:>9} {delta:>+8}  {budget} ({flag})")
for name in base:
    if name not in [r[0] for r in rows]:
        print(f"{name:<12} {'-':>8} {base[name]:>9} {'-':>8}  (missing fixture)")
if failed:
    print("\nsize_report: fixtures over budget:", file=sys.stderr)
    for name, size, old, budget in failed:
        print(f"  {name}: {size} > {budget} (baseline {old})", file=sys.stderr)
    sys.exit(1)
print("\nsize_report: OK")
PY
