# Build the whole PenguScript toolchain on Windows and register its environment.
#
# Layout (inside this checkout):
#   build\psc.exe             compiler
#   build\pengu-bind.exe      optional libclang helper
#   build\lib\*.a             runtime + std_c satellites
#   build\include\*.h         headers
#   build\wasm\...            optional wasm runtime
#   build\env\pengu.env.*     generated PowerShell/CMD environment
#
# The environment is added to the current PowerShell profile (unless
# -NoRegister) so `psc` works from any directory without manually defining
# PENGU_INCLUDE_DIR/PENGU_LIB_DIR/PENGU_STD_DIR.
#
# Usage:
#   .\tools\build.ps1 [-Debug] [-NoBind] [-NoWasm] [-NoRegister] [-CC gcc]
param(
    [switch]$Debug,
    [switch]$NoBind,
    [switch]$NoWasm,
    [switch]$NoRegister,
    [string]$CC = ""
)

$ErrorActionPreference = "Stop"
$Root = Split-Path -Parent $PSScriptRoot
Push-Location $Root
try {
    if ($CC) { $env:CC = $CC }
    $ProfileName = if ($Debug) { "debug" } else { "release" }

    function Write-Log([string]$Message) { Write-Host "[build] $Message" }

    Write-Log "building the native runtime and bootstrap compiler"
    $bootstrapOk = $true
    try {
        & (Join-Path $PSScriptRoot "build_bootstrap.ps1")
        if ($LASTEXITCODE -ne 0) { $bootstrapOk = $false }
    } catch {
        $bootstrapOk = $false
        Write-Warning $_.Exception.Message
    }

    $bootstrap = Join-Path $Root "build\psc-stage0.exe"
    if (-not (Test-Path $bootstrap) -or -not $bootstrapOk) {
        $fallback = Join-Path $Root "build\psc.exe"
        if (Test-Path $fallback) {
            Write-Warning "stage0 bootstrap failed; reusing build\psc.exe as bootstrap"
            $bootstrap = $fallback
        } else {
            throw "cannot bootstrap psc (no build\psc-stage0.exe and no build\psc.exe)"
        }
    }

    Write-Log "building psc ($ProfileName)"
    & $bootstrap build . "--profile=$ProfileName" --no-cache
    if ($LASTEXITCODE -ne 0) { throw "psc build failed" }

    $psc = Join-Path $Root "build\psc.exe"
    & $psc version
    if ($LASTEXITCODE -ne 0) { throw "build\psc.exe version failed" }

    if (-not $NoBind) {
        $llvm = Get-Command "llvm-config" -ErrorAction SilentlyContinue
        if ($llvm -or (Test-Path "C:\Program Files\LLVM")) {
            try {
                & (Join-Path $PSScriptRoot "build_bind.ps1")
                if ($LASTEXITCODE -ne 0) { Write-Warning "pengu-bind was not built (optional)" }
            } catch {
                Write-Warning "pengu-bind was not built (optional): $($_.Exception.Message)"
            }
        } else {
            Write-Warning "libclang not found; skipping the optional pengu-bind helper"
        }
    }

    if (-not $NoWasm) {
        $emcc = Get-Command "emcc" -ErrorAction SilentlyContinue
        if ($emcc) {
            $bash = Get-Command "bash" -ErrorAction SilentlyContinue
            if ($bash) {
                Write-Log "building the WebAssembly runtime"
                & $bash.Source (Join-Path $Root "tools\build_runtime_wasm.sh")
                if ($LASTEXITCODE -ne 0) { Write-Warning "wasm runtime build failed; native builds still work" }
            } else {
                Write-Warning "emcc found but bash is missing; skipping the wasm runtime"
            }
        } else {
            Write-Log "emcc not found; skipping the optional wasm runtime"
        }
    }

    # ------------------------------------------------------------------
    # Generated environment
    # ------------------------------------------------------------------
    $envDir = Join-Path $Root "build\env"
    New-Item -ItemType Directory -Force -Path $envDir | Out-Null
    $rootPs = $Root.Replace("'", "''")
    $envPs = Join-Path $envDir "pengu.env.ps1"
    $envCmd = Join-Path $envDir "pengu.env.cmd"
    $bindPath = Join-Path $Root "build\pengu-bind.exe"
    $wasmDir = Join-Path $Root "build\wasm"

    $psLines = @(
        "# Generated by tools/build.ps1 -- do not edit by hand.",
        "# Dot-source this from PowerShell: . `"$envPs`"",
        "`$env:PENGU_HOME = '$rootPs'",
        "`$env:PENGU_LIB_DIR = Join-Path `$env:PENGU_HOME 'build\\lib'",
        "`$env:PENGU_INCLUDE_DIR = Join-Path `$env:PENGU_HOME 'build\\include'",
        "`$env:PENGU_STD_DIR = Join-Path `$env:PENGU_HOME 'std'",
        "`$env:PENGU_PSC = Join-Path `$env:PENGU_HOME 'build\\psc.exe'"
    )
    if (Test-Path $bindPath) {
        $psLines += "`$env:PENGU_BIND = Join-Path `$env:PENGU_HOME 'build\\pengu-bind.exe'"
    }
    if (Test-Path $wasmDir) {
        $psLines += "`$env:PENGU_RUNTIME_CROSS = Join-Path `$env:PENGU_HOME 'build\\wasm'"
    }
    $psLines += @(
        "`$penguBin = Join-Path `$env:PENGU_HOME 'build'",
        "if ((`$env:PATH -split ';') -notcontains `$penguBin) {",
        "    `$env:PATH = `$penguBin + ';' + `$env:PATH",
        "}"
    )
    Set-Content -LiteralPath $envPs -Value $psLines -Encoding utf8

    $cmdLines = @(
        "@echo off",
        "rem Generated by tools/build.ps1 -- do not edit by hand.",
        "set `"PENGU_HOME=$Root`"",
        "set `"PENGU_LIB_DIR=%PENGU_HOME%\build\lib`"",
        "set `"PENGU_INCLUDE_DIR=%PENGU_HOME%\build\include`"",
        "set `"PENGU_STD_DIR=%PENGU_HOME%\std`"",
        "set `"PENGU_PSC=%PENGU_HOME%\build\psc.exe`""
    )
    if (Test-Path $bindPath) { $cmdLines += "set `"PENGU_BIND=%PENGU_HOME%\build\pengu-bind.exe`"" }
    if (Test-Path $wasmDir) { $cmdLines += "set `"PENGU_RUNTIME_CROSS=%PENGU_HOME%\build\wasm`"" }
    $cmdLines += "set `"PATH=%PENGU_HOME%\build;%PATH%`""
    Set-Content -LiteralPath $envCmd -Value $cmdLines -Encoding ascii

    Write-Log "environment written to build\env\"

    # ------------------------------------------------------------------
    # Register in the user PowerShell profile
    # ------------------------------------------------------------------
    $registered = $false
    if (-not $NoRegister) {
        $coreDir = if ($env:LOCALAPPDATA) {
            Join-Path $env:LOCALAPPDATA "pengu"
        } else {
            Join-Path $HOME ".config\pengu"
        }
        New-Item -ItemType Directory -Force -Path $coreDir | Out-Null
        $coreEnv = Join-Path $coreDir "env.ps1"
        Copy-Item -LiteralPath $envPs -Destination $coreEnv -Force
        $coreCmd = Join-Path $coreDir "env.cmd"
        Copy-Item -LiteralPath $envCmd -Destination $coreCmd -Force

        $profilePath = $PROFILE.CurrentUserCurrentHost
        if (-not $profilePath) {
            $profilePath = Join-Path $HOME "Documents\PowerShell\Microsoft.PowerShell_profile.ps1"
        }
        $profileDir = Split-Path -Parent $profilePath
        if ($profileDir) { New-Item -ItemType Directory -Force -Path $profileDir | Out-Null }
        if (-not (Test-Path $profilePath)) { New-Item -ItemType File -Force -Path $profilePath | Out-Null }

        $begin = "# >>> PenguScript toolchain >>>"
        $end = "# <<< PenguScript toolchain <<<"
        $kept = New-Object System.Collections.Generic.List[string]
        $skip = $false
        foreach ($line in (Get-Content -LiteralPath $profilePath)) {
            if ($line -eq $begin) { $skip = $true; continue }
            if ($line -eq $end) { $skip = $false; continue }
            if (-not $skip) { $kept.Add($line) }
        }
        $kept.Add($begin)
        $kept.Add("if (Test-Path `"$coreEnv`") { . `"$coreEnv`" }")
        $kept.Add($end)
        Set-Content -LiteralPath $profilePath -Value $kept -Encoding utf8
        $registered = $true
        Write-Log "registered the toolchain environment in $profilePath"
    }

    # ------------------------------------------------------------------
    # Summary
    # ------------------------------------------------------------------
    & $psc version
    Write-Log "compiler:  $psc"
    Write-Log "runtime:   $(Join-Path $Root 'build\lib\libpengu_runtime.a')"
    Write-Log "headers:   $(Join-Path $Root 'build\include')"
    Write-Log "std:       $(Join-Path $Root 'std')"
    if (Test-Path $bindPath) { Write-Log "bind:      $bindPath" }

    Write-Host ""
    Write-Host "Open a new PowerShell window (or reload the profile) and run:"
    Write-Host "  psc version"
    Write-Host "  psc build C:\path\to\project"
    Write-Host ""
    if ($registered) {
        Write-Host "PowerShell profile: $profilePath"
    } else {
        Write-Host "Dot-source the environment before using psc:"
        Write-Host "  . `"$envPs`""
    }
    Write-Host "CMD: call `"$envCmd`""
} finally {
    Pop-Location
}
