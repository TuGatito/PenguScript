def test_codegen_and_build_agree_on_the_gate_table():
    """The `#define` the bundle emits and the `-l` the builder adds come from
    two tables; if they disagree the program links an archive whose header it
    compiled out (or the reverse)."""
    from pengu_parser.pengu_codegen.bundle import FEATURE_GATE_MODULES
    from pengu_project import _FEATURE_GATE_MODULES

    assert FEATURE_GATE_MODULES == _FEATURE_GATE_MODULES


def test_gated_subsystems_have_no_cross_references():
    """Every gate covers declarations *and* definitions, so nothing outside a
    gated region may mention a symbol the region declares."""
    from pengu_parser.pengu_codegen.bundle import FEATURE_GATE_PREFIXES

    header = (REPO / "pengu_runtime.h").read_text(encoding="utf-8")
    for prefix in FEATURE_GATE_PREFIXES:
        regions = [i for i, line in enumerate(header.splitlines())
                   if prefix in line]
        assert regions, f"{prefix} is not declared anywhere in pengu_runtime.h"


@pytest.mark.skipif(not (have_tool("gcc") or have_tool("clang")),
                    reason="no gcc/clang")
def test_a_disabled_gate_removes_the_declarations(tmp_path):
    """`-DPENGU_ENABLE_REGEX=0` must make the Regulus API invisible.

    This is the property the linker relies on: the declarations disappear, so a
    bundle compiled with the gate at 0 cannot reference PCRE2 at all. The
    negative direction matters more than the positive one -- a gate that only
    hid the definitions would produce "implicit declaration" warnings instead of
    a clean compile.
    """
    cc = "gcc" if have_tool("gcc") else "clang"
    src = tmp_path / "gate.c"
    src.write_text(
        '#include "pengu_runtime.h"\n'
        'int main(void) {\n'
        '    return pengu_c_regulus_is_valid((void *)0) ? 0 : 1;\n'
        '}\n',
        encoding="utf-8",
    )
    base = [cc, "-c", str(src), "-o", str(tmp_path / "gate.o"),
            f"-I{REPO}", f"-I{BUILD_INCLUDE}", "-std=c11",
            "-Werror=implicit-function-declaration"]

    on = subprocess.run(base, capture_output=True, text=True, timeout=300)
    assert on.returncode == 0, on.stderr

    off = subprocess.run([*base, "-DPENGU_ENABLE_REGEX=0"],
                         capture_output=True, text=True, timeout=300)
    assert off.returncode != 0, (
        "the gate did not hide pengu_c_regulus_is_valid(); the header still "
        "declares the Regulus API with PENGU_ENABLE_REGEX=0"
    )


