"""Binary-size reduction: section GC, conditional linking, ``PENGU_ENABLE_*``.

PenguScript 2.0 shipped a 659.5 KiB ``hello_world`` because three things
compounded:

1. ``libpengu_runtime.a`` had a single object member, so any reference to it
   dragged in the whole runtime, which in turn referenced PCRE2, libxml2,
   libcurl, mbedtls, libmicrohttpd and zlib;
2. those six archives were linked unconditionally;
3. nothing was compiled with ``-ffunction-sections``, so ``--gc-sections`` had
   nothing to prune.

Phase 1 moved every external binding out of the tree: the core runtime now
needs nothing beyond libc/libm/pthreads and links **no** native archive. The
section-splitting machinery and the one remaining gate (``PENGU_ENABLE_THREADS``
for ``std.filum``) stay in place.

These tests pin each fix at the level where it is observable:

* the *profiles* carry the section-splitting flags and a ``small`` profile
  exists (pure configuration, no toolchain needed);
* the *link line* keeps the runtime, always emits the section-GC option, and
  links no native archive at all;
* the *runtime header* really hides a gated subsystem's declarations when the
  gate is 0;
* the *end-to-end* result: a built, stripped ``hello_world`` is small.

Nothing here inspects generated C (rule 1 in AGENT_TESTING.md); the artifact and
the link line are the observable contract.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
from pathlib import Path
from typing import List, Sequence

import pytest

from tests.conftest import BUILD_INCLUDE, REPO, have_tool, requires_cc, requires_runtime

PENGU = [sys.executable, str(REPO / "pengu_project.py")]

#: The target this work was specified against. The measured value is ~14.3 KiB;
#: the assertion is the budget, not the measurement, so unrelated compiler
#: changes do not turn it red.
HELLO_BUDGET_BYTES = 130 * 1024

_HELLO = (
    'weave main into int:\n'
    '    var msg as string is "Hello, world!"\n'
    '    calling print with msg\n'
    '    return 0\n'
)


def _run(args: List[str], cwd: Path, env=None) -> subprocess.CompletedProcess:
    return subprocess.run([*PENGU, *args], capture_output=True, text=True,
                          timeout=300, cwd=str(cwd), env=env)


def _builder(tmp_path: Path, source: str = None):
    """A `PenguBuilder` for a throw-away project; no bundle is generated."""
    from pengu_project import OutputType, PenguBuilder, ProjectConfig

    script = tmp_path / "probe.pengu"
    script.write_text(source or "weave main into int:\n    return 0\n", encoding="utf-8")
    build_dir = tmp_path / "probe_build"
    build_dir.mkdir(parents=True, exist_ok=True)
    cfg = ProjectConfig(entry=str(script), base_dir=str(tmp_path),
                        output=OutputType.EXE, output_name="probe", name="probe",
                        build_dir=str(build_dir), profile="release")
    cfg.links = ["pengu_runtime"]
    return PenguBuilder(cfg)


def _probe_bundle(*std_modules: str, symbols: Sequence[str] = ()) -> str:
    """A stand-in for a generated bundle, holding only the marker, the module
    ``#line`` comments and whichever subsystem symbols the caller wants.

    The archive decision is a pure function of that text, so this exercises it
    without paying for a semantic check of the real `std` module graph.
    """
    lines = ["/* Auto-generated by PenguScript */", '#include "pengu_runtime.h"']
    for name in std_modules:
        lines.append(f'#line 1 "/repo/std/{name}.pengu"')
    for symbol in symbols:
        lines.append(f"  {symbol};")
    lines.append("int main(void) { return 0; }")
    return "\n".join(lines) + "\n"


def _link_tokens(tmp_path: Path, source: str) -> List[str]:
    """Compiles *source* to ``OutputType.EXE`` far enough to get the link argv.

    The bundle is written and the command list assembled, but the compiler is
    never invoked: this is a build-policy assertion, and it needs no toolchain.
    """
    builder = _builder(tmp_path, source)
    build_dir = tmp_path / "probe_build"
    bundle_file, _ = builder.bundle(output_file=str(build_dir / "probe.c"))
    commands = builder.build_compile_commands(bundle_file, str(build_dir / "probe"))
    tokens: List[str] = []
    for command in commands:
        tokens.extend(command)
    return tokens


def _links(tokens: List[str], archive: str) -> bool:
    return f"-l{archive}" in tokens


