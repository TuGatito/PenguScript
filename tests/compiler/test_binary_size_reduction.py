def test_section_splitting_flags_are_the_same_constant_everywhere():
    """`pengu_project` and `build_runtime` must not drift apart.

    The link step's `--gc-sections` can only drop a function if the archive that
    holds it was compiled with `-ffunction-sections`. A single flag spelled two
    ways is how that guarantee gets lost.
    """
    import build_runtime
    from pengu_project import SECTION_FLAGS

    assert SECTION_FLAGS == ["-ffunction-sections", "-fdata-sections"]
    assert build_runtime.SECTION_FLAGS == SECTION_FLAGS


def test_default_profiles_split_sections_and_expose_small():
    from pengu_project import ProjectConfig

    profiles = ProjectConfig().profiles
    for name in ("release", "small"):
        cflags = profiles[name]["cflags"]
        assert "-ffunction-sections" in cflags, name
        assert "-fdata-sections" in cflags, name
    small = profiles["small"]["cflags"]
    assert "-Os" in small
    assert "-fno-asynchronous-unwind-tables" in small
    assert "-fno-unwind-tables" in small
    assert "-fno-ident" in small
    assert "-fno-plt" in small
    assert "PENGU_SIZE_OPT" in profiles["small"]["defines"]


def test_the_init_template_writes_the_section_flags(tmp_path):
    """A freshly initialised project must get the flags without editing anything."""
    res = _run(["init", "tpl", "--type", "exe", "--links", "pengu_runtime"], cwd=tmp_path)
    assert res.returncode == 0, res.stderr
    manifest = (tmp_path / "tpl" / "pengu.toml").read_text(encoding="utf-8")
    assert "[profiles.small]" in manifest
    release = manifest.split("[profiles.release]", 1)[1].split("[profiles.small]", 1)[0]
    assert "-ffunction-sections" in release
    assert "-fdata-sections" in release


