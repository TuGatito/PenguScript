@requires_cc
@requires_runtime
def test_stripped_hello_world_fits_the_size_budget(tmp_path):
    """The whole point of the exercise, measured on the real artifact."""
    res = _run(["init", "tiny", "--type", "exe", "--links", "pengu_runtime"], cwd=tmp_path)
    assert res.returncode == 0, res.stderr
    project = tmp_path / "tiny"
    (project / "src" / "main.pengu").write_text(_HELLO, encoding="utf-8")

    res = _run(["build", "--profile", "release", "--verbose"], cwd=project)
    assert res.returncode == 0, res.stdout + res.stderr
    log = res.stdout + res.stderr
    assert "native archives linked: (none)" in log, log

    binary = project / "build" / ("tiny.exe" if os.name == "nt" else "tiny")
    assert binary.is_file(), binary
    strip = "strip"
    if os.name != "nt" and have_tool(strip):
        subprocess.run([strip, str(binary)], check=False, capture_output=True, timeout=60)
    size = binary.stat().st_size
    assert size <= HELLO_BUDGET_BYTES, (
        f"stripped hello_world is {size} bytes, over the "
        f"{HELLO_BUDGET_BYTES}-byte budget (it was 675_000+ before 2.0)"
    )

    run = subprocess.run([str(binary)], capture_output=True, text=True, timeout=60)
    assert run.returncode == 0, run.stderr
    assert "Hello, world!" in run.stdout


